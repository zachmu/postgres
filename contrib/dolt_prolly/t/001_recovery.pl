use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('prolly');
$node->init;
$node->append_conf('postgresql.conf', "max_parallel_workers_per_gather=0\nmax_prepared_transactions=10\n");
$node->start;
$node->safe_psql('postgres',q{
CREATE EXTENSION dolt_prolly;
CREATE TABLE p(id int PRIMARY KEY,v text COLLATE "C") USING dolt_prolly_table;
CREATE TABLE normal(id int);
INSERT INTO p VALUES(1,'initial');
CREATE TABLE large_chunk(v text COLLATE "C") USING dolt_prolly_table;
INSERT INTO large_chunk VALUES(repeat('z',20000));
});
my $reader=$node->background_psql('postgres');
$reader->query_safe('BEGIN ISOLATION LEVEL REPEATABLE READ; SELECT * FROM p');
$node->safe_psql('postgres',q{INSERT INTO p VALUES(2,'committed')});
is($reader->query_safe('SELECT count(*) FROM p'),'1','old snapshot retains old root');
$reader->query_safe('COMMIT');
is($reader->query_safe('SELECT count(*) FROM p'),'2','new snapshot sees committed root');
$reader->quit;
my $before=$node->safe_psql('postgres',q{SELECT dolt_prolly_root('p')});
$node->safe_psql('postgres',q{BEGIN; INSERT INTO p VALUES(3,'abort'); INSERT INTO normal VALUES(3); ROLLBACK});
is($node->safe_psql('postgres',q{SELECT dolt_prolly_root('p')}),$before,'rollback preserves canonical root');
$node->safe_psql('postgres',q{BEGIN; INSERT INTO p VALUES(4,'prepared'); INSERT INTO normal VALUES(4); PREPARE TRANSACTION 'prolly_prepared'});
my $writer=$node->background_psql('postgres');
# Prepared transaction holds the table write lock, so use a different table for crash-aborted work.
$writer->query_safe(q{CREATE TABLE abandoned(id int) USING dolt_prolly_table; BEGIN; INSERT INTO abandoned VALUES(99)});
$node->stop('immediate');
$writer->quit;
$node->start;
is($node->safe_psql('postgres',q{SET enable_seqscan=off; SELECT string_agg(id::text,',' ORDER BY id) FROM p}),'1,2','recovery exposes committed index and table roots only');
is($node->safe_psql('postgres',q{SELECT count(*) FROM abandoned}),'0','crash-aborted root remains invisible');
is($node->safe_psql('postgres',q{SELECT length(v) FROM large_chunk}),'20000','fragmented chunk recovers across relation pages');
is($node->safe_psql('postgres',q{SELECT count(*) FROM normal}),'0','prepared ordinary heap changes remain invisible');
$node->safe_psql('postgres',q{COMMIT PREPARED 'prolly_prepared'});
is($node->safe_psql('postgres',q{SET enable_seqscan=off; SELECT v FROM p WHERE id=4}),'prepared','prepared table/index publication recovers');
is($node->safe_psql('postgres',q{SELECT id FROM normal}),'4','mixed heap and prolly commit together');
$node->safe_psql('postgres',q{BEGIN; UPDATE p SET v='updated' WHERE id=1; DELETE FROM p WHERE id=2; COMMIT});
my $root=$node->safe_psql('postgres',q{SELECT dolt_prolly_root('p')});
$node->stop('immediate'); $node->start;
is($node->safe_psql('postgres',q{SELECT dolt_prolly_root('p')}),$root,'root hash survives repeated crash recovery');
is($node->safe_psql('postgres',q{SET enable_seqscan=off; SELECT string_agg(id::text||':'||v,',' ORDER BY id) FROM p}),'1:updated,4:prepared','updates and deletes recover with index maintenance');
$node->stop;
done_testing();
