use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('catalog_binding');
$node->init(allows_streaming=>1,extra=>['--encoding=UTF8','--locale=C']);
$node->append_conf('postgresql.conf',"max_prepared_transactions=10\nmax_parallel_workers_per_gather=0\n");
$node->start;
sub sql {$node->safe_psql('postgres',$_[0]);}
sub fails {my($query,$pattern,$label)=@_;my($status,$out,$err)=$node->psql('postgres',$query);isnt($status,0,$label);like($err,$pattern,"$label diagnostic");}
sql(q{CREATE TABLE t(id int PRIMARY KEY,v int) USING dolt_prolly_table; INSERT INTO t VALUES(1,10); CREATE INDEX t_v_idx ON t USING dolt_prolly_index(v)});
my $old=sql(q{SELECT dolt_commit('-Am','integer schema')});
my $oldshort=substr($old,0,12);
fails(qq{SELECT * FROM "postgres\@${oldshort}".public.t},qr/not materialized/,'lookup never creates catalog objects');
is(sql("SELECT dolt_catalog_materialize('$old')"),$old,'materialize retained canonical schema and data');
sql("SELECT dolt_branch('historical')");
my $oldoid=sql(qq{SELECT tableoid FROM "postgres\@${oldshort}".public.t});
is(sql(qq{SELECT * FROM "postgres\@${oldshort}".public.t}),'1|10','read old schema');
my $reader=$node->background_psql('postgres');
$reader->query_safe(qq{PREPARE old_plan AS SELECT v FROM "postgres\@${oldshort}".public.t});
# Live DDL can proceed independently of an immutable projected reader.
$reader->query_safe('BEGIN ISOLATION LEVEL REPEATABLE READ');
is($reader->query_safe('EXECUTE old_plan'),'10','old descriptor and data bound');
sql(q{SET lock_timeout='1s'; DROP TABLE t; CREATE TABLE t(id int PRIMARY KEY,v text COLLATE "C",note text) USING dolt_prolly_table; INSERT INTO t VALUES(1,'ten','new schema')});
my $new=sql(q{SELECT dolt_commit('-Am','text schema')});
my $newshort=substr($new,0,12);
sql("SELECT dolt_catalog_materialize('$new')");
is($reader->query_safe('EXECUTE old_plan'),'10','source DDL does not invalidate retained schema identity');
$reader->query_safe('COMMIT');
is(sql(qq{SELECT a.v,b.v,b.note,pg_typeof(a.v),pg_typeof(b.v),a.tableoid<>b.tableoid FROM "postgres\@${oldshort}".public.t a JOIN "postgres\@${newshort}".public.t b USING(id)}),'10|ten|new schema|integer|text|t','incompatible schemas and types coexist within one query');
is(sql(qq{SELECT (ROW(2,20)::"postgres\@${oldshort}".public.t).v}),'20','qualified row type uses matching projection');
is(sql(qq{SET enable_seqscan=off; SELECT v FROM "postgres\@${oldshort}".public.t WHERE id=1}),'10','index fetch uses retained projection data binding');
sql("SELECT dolt_catalog_materialize('$old')");
is(sql(qq{SELECT tableoid FROM "postgres\@${oldshort}".public.t}),$oldoid,'repeated materialization reuses runtime identities');
is(sql(q{SELECT count(*) FROM dolt_diff_summary('HEAD','WORKING')}),'0','runtime projections do not enter canonical capture');
fails(qq{UPDATE "postgres\@${oldshort}".public.t SET v=30},qr/read-only/,'retained data immutable');
fails(qq{DROP TABLE "postgres\@${oldshort}".public.t},qr/read-only/,'retained definition immutable');
fails(qq{TRUNCATE "postgres\@${oldshort}".public.t},qr/read-only/,'truncate cannot erase retained storage');
# Materialization is transactional, including namespace/type/index/data creation.
sql(q{INSERT INTO t VALUES(2,'two','later')});
my $later=sql(q{SELECT dolt_commit('-Am','later')});
my $latershort=substr($later,0,12);
my $before=sql('SELECT count(*) FROM pg_dolt_projection');
fails("BEGIN ISOLATION LEVEL REPEATABLE READ; SELECT dolt_catalog_materialize('$later')",qr/READ COMMITTED/,'materialization does not replace a transaction snapshot');

sql("BEGIN; SELECT dolt_catalog_materialize('$later'); ROLLBACK");
is(sql('SELECT count(*) FROM pg_dolt_projection'),$before,'rollback removes projection mapping');
fails(qq{SELECT * FROM "postgres\@${latershort}".public.t},qr/not materialized/,'rolled back runtime schema not visible');
# A future publisher can prepare schema + roots + ref CAS together.
my $publisher=$node->background_psql('postgres');
$publisher->query_safe('BEGIN');
$publisher->query_safe("SELECT dolt_catalog_materialize('$later')");
fails("SET lock_timeout='100ms'; SELECT dolt_catalog_materialize('$later')",qr/lock timeout/,'same-generation publishers serialize');
is(sql("SET lock_timeout='100ms'; SELECT dolt_catalog_materialize('$old')"),$old,'independent generation lookup does not wait for publisher');
$publisher->query_safe("SELECT dolt_manifest_cas('heads/published',NULL,decode('$later','hex'))");
$publisher->query_safe(q{PREPARE TRANSACTION 'catalog_publish'});$publisher->quit;$reader->quit;
is(sql(q{SELECT count(*) FROM pg_dolt_ref WHERE refname='heads/published'}),'0','prepared ref invisible');
is(sql('SELECT count(*) FROM pg_dolt_projection'),$before,'prepared runtime mapping invisible');
$node->stop('immediate');$node->start;
is(sql(q{SELECT count(*) FROM pg_dolt_ref WHERE refname='heads/published'}),'0','prepared publication invisible after crash');
sql(q{COMMIT PREPARED 'catalog_publish'});
is(sql(qq{SELECT count(*) FROM "postgres/published".public.t}),'2','catalog, roots and ref publish together after recovery');
is(sql(qq{SELECT * FROM "postgres\@${oldshort}".public.t}),'1|10','older schema and data survive recovery');

my $physical=sql("SELECT n.nspname FROM pg_dolt_projection p JOIN pg_namespace n ON n.oid=p.runtime_namespace WHERE p.commit_hash=decode('$old','hex') AND logical_namespace='public'");
is(sql("SELECT count(*) FROM pg_indexes WHERE schemaname='$physical'"),'2','primary and secondary indexes reconstructed');
fails("DROP SCHEMA $physical CASCADE",qr/read-only/,'cascade cannot delete retained generation');
fails("ALTER SCHEMA $physical RENAME TO erased",qr/read-only/,'runtime namespace identity immutable');
is(sql(qq{BEGIN READ ONLY; SELECT v FROM "postgres\@${oldshort}".public.t; COMMIT}),'10','historical lookup works in read-only transaction');
is(sql("SELECT v FROM public.t AS OF '$old'"),'10','AS OF accepts full commit hashes without identifier truncation');
is(sql("SET search_path=pg_catalog,public; SELECT v FROM t AS OF '$old'"),'10','AS OF searches logical namespaces');
my $moving=$node->background_psql('postgres');
$moving->query_safe(q{PREPARE moving AS SELECT v::text COLLATE "C" FROM "postgres/historical".public.t});
is($moving->query_safe('EXECUTE moving'),'10','named prepared binding before HEAD moves');
$moving->query_safe('BEGIN ISOLATION LEVEL REPEATABLE READ');
is($moving->query_safe('EXECUTE moving'),'10','repeatable read pins old ref');
sql("SELECT dolt_manifest_cas('heads/historical',(SELECT reftoken FROM pg_dolt_ref WHERE refname='heads/historical'),decode('$new','hex'))");
is($moving->query_safe('EXECUTE moving'),'10','ref invalidation respects repeatable-read snapshot');
$moving->query_safe('COMMIT');
is($moving->query_safe('EXECUTE moving'),'ten','named prepared query rebinds at next snapshot');
$moving->quit;
fails("PREPARE changed AS SELECT v FROM \"postgres/historical\".public.t; SELECT dolt_manifest_cas('heads/historical',(SELECT reftoken FROM pg_dolt_ref WHERE refname='heads/historical'),decode('$old','hex')); EXECUTE changed",qr/cached plan must not change result type/,'prepared descriptor changes fail explicitly');
sql("SELECT dolt_checkout('main')");
is(sql("SELECT v FROM t AS OF '$old'"),'10','session checkout does not redirect historical storage');
$node->backup('catalog_backup');
my $standby=PostgreSQL::Test::Cluster->new('catalog_standby');
$standby->init_from_backup($node,'catalog_backup',has_streaming=>1);
$standby->start;
is($standby->safe_psql('postgres',"SELECT v FROM t AS OF '$old'"),'10','already materialized history readable on standby without catalog writes');
$standby->stop;
$node->stop;done_testing();
