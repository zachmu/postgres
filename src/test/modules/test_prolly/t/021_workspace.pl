use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('workspace');
$node->init(extra=>['--encoding=UTF8','--locale=C']);
$node->append_conf('postgresql.conf',"max_parallel_workers_per_gather=0\n");
$node->start;
sub sql { $node->safe_psql('postgres',$_[0]); }
sub fails {
 my($q,$pat,$label)=@_;my($status,$out,$err)=$node->psql('postgres',$q);
 isnt($status,0,$label);like($err,$pat,"$label diagnostic");
}
# Named staging, unstaging, clean and table checkout on an untracked table.
sql(q{CREATE TABLE t1(pk int PRIMARY KEY) USING dolt_prolly_table; INSERT INTO t1 VALUES(1)});
sql(q{CREATE TABLE t2(pk int PRIMARY KEY) USING dolt_prolly_table});
is(sql(q{SELECT dolt_add('t1')}),'0','stage one table');
is(sql(q{SELECT * FROM dolt.status ORDER BY table_name}),"public.t1|t|new table\npublic.t2|f|new table",'only the named table is staged');
is(sql(q{SELECT dolt_reset('t1')}),'0','unstage one table');
is(sql(q{SELECT * FROM dolt.status WHERE staged}),'','table unstaged');
sql(q{SELECT dolt_add('t1','t2')});
is(sql(q{SELECT count(*) FROM dolt.status WHERE staged}),'2','multiple named tables staged');
is(sql(q{SELECT dolt_reset()}),'0','unstage everything');
is(sql(q{SELECT count(*) FROM dolt.status WHERE staged}),'0','nothing staged');
is(sql(q{SELECT dolt_clean('--dry-run')}),'0','dry run');
is(sql(q{SELECT count(*) FROM dolt.status}),'2','dry run keeps untracked tables');
is(sql(q{SELECT dolt_clean('t2')}),'0','clean one untracked table');
is(sql(q{SELECT * FROM dolt.status}),'public.t1|f|new table','named table dropped');
is(sql(q{SELECT status,message FROM dolt_checkout('t1')}),'0|','checkout of an untracked table');
is(sql(q{SELECT count(*) FROM dolt.status}),'0','untracked table removed by checkout');
fails(q{SELECT dolt_checkout('nothing')},qr/tablespec 'nothing' did not match any table/,'unknown branch or table');
fails(q{SELECT dolt_checkout('')},qr/cannot checkout empty string/,'empty checkout');
# Committed history for reset, revert and cherry-pick.
sql(q{CREATE TABLE t(pk int PRIMARY KEY,v text COLLATE "C") USING dolt_prolly_table; INSERT INTO t VALUES(1,'one'),(2,'two')});
my $c1=sql(q{SELECT dolt_commit('-Am','first')});
sql(q{UPDATE t SET v='TWO' WHERE pk=2; INSERT INTO t VALUES(3,'three')});
my $c2=sql(q{SELECT dolt_commit('-Am','second')});
sql(q{UPDATE t SET v='ONE' WHERE pk=1});
is(sql(q{SELECT * FROM dolt.status}),'public.t|f|modified','dirty before checkout');
is(sql(q{SELECT status FROM dolt_checkout('t')}),'0','table checkout restores head contents');
is(sql(q{SELECT v FROM t WHERE pk=1}),'one','row restored');
is(sql(q{SELECT count(*) FROM dolt.status}),'0','clean after checkout');
sql(q{DELETE FROM t WHERE pk=3; CREATE TABLE extra(id int PRIMARY KEY) USING dolt_prolly_table});
is(sql(q{SELECT dolt_reset('--hard','HEAD')}),'0','hard reset to head');
is(sql(q{SELECT count(*) FROM t}),'3','hard reset restores rows');
is(sql(q{SELECT count(*) FROM dolt.status}),'0','hard reset drops untracked tables');
is(sql(q{SELECT dolt_reset('--hard','HEAD~1')}),'0','hard reset to an earlier commit');
is(sql("SELECT commit_hash=\'$c1\' FROM dolt_log('-n','1')"),'t','hard reset moves head');
is(sql(q{SELECT string_agg(v,',' ORDER BY pk) FROM t}),'one,two','hard reset restores earlier contents');
is(sql(q{SELECT count(*) FROM dolt.status}),'0','clean after hard reset');
is(sql("SELECT dolt_reset('--soft','$c2')"),'0','soft reset forward');
is(sql("SELECT commit_hash=\'$c2\' FROM dolt_log('-n','1')"),'t','soft reset moves head');
is(sql(q{SELECT * FROM dolt.status WHERE staged}),'public.t|t|modified','soft reset leaves staging and working alone');
is(sql("SELECT dolt_reset('$c1')"),'0','mixed reset to a revision');
is(sql(q{SELECT count(*) FROM dolt.status WHERE staged}),'0','mixed reset moves staging to the revision');
is(sql(q{SELECT count(*) FROM dolt.status WHERE NOT staged}),'0','mixed reset leaves working data alone');
fails(q{SELECT dolt_reset('--hard','--soft')},qr/mutually exclusive/,'incompatible reset flags');
sql("SELECT dolt_reset('--hard','$c2')");
sql(q{INSERT INTO t VALUES(4,'four')});
my $c3=sql(q{SELECT dolt_commit('-Am','third')});
like(sql(q{SELECT substring(dolt_revert('HEAD')::text,42)}),qr/^,0,0,0\)$/,'revert returns hash and zero conflict counts');
is(sql(q{SELECT message FROM dolt_log('-n','1')}),'Revert "third"','revert commit message');
is(sql(q{SELECT count(*) FROM t WHERE pk=4}),'0','revert undid the insert');
is(sql(q{SELECT count(*) FROM dolt.status}),'0','revert leaves a clean working set');
fails(q{SELECT dolt_revert(dolt_hashof('HEAD~5'))},qr/invalid ancestor spec/,'revert of an impossible revision');
sql(q{SELECT dolt_branch('side','HEAD~1')});
my $s=$node->background_psql('postgres',on_error_stop=>0);
$s->query_safe(q{SELECT dolt_checkout('side')});
is($s->query_safe(q{SELECT count(*) FROM t}),'4','side branch at third commit');
is($s->query_safe("SELECT dolt_cherry_pick('$c3')::text LIKE '(%,0,0,0)'"),'t','cherry-pick onto a branch that already has the row');
$s->query_safe(q{SELECT dolt_reset('--hard','HEAD~2')});
is($s->query_safe(q{SELECT count(*) FROM t}),'3','side reset before the insert');
is($s->query_safe("SELECT dolt_cherry_pick('$c3')::text LIKE '(%,0,0,0)'"),'t','cherry-pick applies the commit');
is($s->query_safe(q{SELECT v FROM t WHERE pk=4}),'four','cherry-picked row present');
is($s->query_safe(q{SELECT message FROM dolt_log('-n','1')}),'third','cherry-pick keeps the message');
$s->query_safe(q{INSERT INTO t VALUES(5,'five')});
my($out,$err)=$s->query(q{SELECT dolt_cherry_pick('main')});
is($err,1,'cherry-pick requires a clean working set');
$s->{stderr} = '';
$s->query_safe(q{SELECT dolt_checkout('t')});
$s->quit;
# Branch management and commit-graph helpers.
is(sql(q{SELECT dolt_branch('-c','main','copy')}),'0','copy branch');
is(sql(q{SELECT dolt_branch('-c','-f','side','copy')}),'0','force copy over existing branch');
is(sql(q{SELECT dolt_hashof('copy')=dolt_hashof('side')}),'t','forced copy points at the source');
fails(q{SELECT dolt_branch('-c','main','copy')},qr/already exists/,'copy without force rejected');
is(sql(q{SELECT dolt_branch('-m','copy','renamed')}),'0','rename branch');
is(sql(q{SELECT string_agg(name,',' ORDER BY name) FROM dolt.branches}),'main,renamed,side','rename replaces the old name');
fails(q{SELECT dolt_branch('-d','main')},qr/Cannot delete checked out branch 'main'/,'cannot delete session branch');
is(sql(q{SELECT dolt_branch('-d','renamed')}),'0','delete branch');
is(sql(q{SELECT dolt_branch('-D','side')}),'0','force delete branch');
is(sql(q{SELECT string_agg(name,',' ORDER BY name) FROM dolt.branches}),'main','deleted branches gone');
fails(q{SELECT dolt_checkout('side')},qr/did not match any table/,'deleted branch is unknown');
sql(q{SELECT dolt_branch('b1','HEAD~1')});
is(sql(q{SELECT * FROM dolt_branch_status('main','b1')}),'b1|0|1','branch status behind');
is(sql(q{SELECT * FROM dolt_branch_status('b1','main')}),'main|1|0','branch status ahead');
is(sql(q{SELECT * FROM dolt_count_commits('--from','b1','--to','main')}),'1|0','count commits');
is(sql(q{SELECT dolt_merge_base('main','b1')=dolt_hashof('b1')}),'t','merge base');
is(sql(q{SELECT dolt_version() LIKE '%-dolt'}),'t','version string');
is(sql(q{SELECT length(dolt_hashof_table('t')),dolt_hashof_db()=dolt_hashof_db('HEAD'),dolt_hashof_db('STAGED')=dolt_hashof_db('HEAD')}),'40|t|t','database and table hashes');
sql(q{INSERT INTO t VALUES(9,'nine')});
is(sql(q{SELECT dolt_hashof_db()=dolt_hashof_db('HEAD')}),'f','working hash reflects live changes');
sql(q{SELECT dolt_checkout('t')});
sql(q{SELECT dolt_tag('v1','HEAD','-m','release')});
is(sql(q{SELECT tag_name FROM dolt.tags}),'v1','tag created');
fails(q{SELECT dolt_checkout('v1')},qr/detached head/,'tag checkout rejected');
is(sql(q{SELECT dolt_tag('-d','v1')}),'0','tag deleted');
is(sql(q{SELECT count(*) FROM dolt.tags}),'0','tag gone');
is(sql(q{SELECT ref,commit_message FROM dolt_reflog('main') LIMIT 1}),'refs/heads/main|Revert "third"','reflog newest first');
is(sql(q{SELECT count(*)>=7 FROM dolt_reflog('main')}),'t','reflog records every head move');
is(sql(q{SELECT count(*)>0 FROM dolt_reflog() WHERE ref='refs/tags/v1'}),'t','reflog keeps tag history');
is(sql(q{SELECT ref FROM dolt_reflog('b1')}),'refs/heads/b1','reflog of another branch');
$node->stop;
done_testing();
