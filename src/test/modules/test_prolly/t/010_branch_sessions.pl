use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('branch_sessions');
$node->init(extra=>['--encoding=UTF8','--locale=C']);
$node->append_conf('postgresql.conf',"max_prepared_transactions=10\nmax_parallel_workers_per_gather=0\n");
$node->start;
sub sql { $node->safe_psql('postgres',$_[0]); }
sql(q{CREATE TABLE t(id int PRIMARY KEY,v int) USING dolt_prolly_table; INSERT INTO t VALUES(1,10)});
sql(q{SELECT dolt_commit('-Am','base')});
my $a=$node->background_psql('postgres');
my $b=$node->background_psql('postgres');
$a->query_safe(q{SELECT dolt_checkout('-b','feature')});
$b->query_safe(q{SELECT dolt_checkout('feature')});
$a->query_safe('PREPARE read_t(int) AS SELECT v FROM t WHERE id=$1');
is($a->query_safe('EXECUTE read_t(1)'),'10','prepared plan on branch base');
$b->query_safe('BEGIN ISOLATION LEVEL REPEATABLE READ');
is($b->query_safe('SELECT v FROM t'),'10','repeatable snapshot on fallback history root');
$a->query_safe('UPDATE t SET v=20');
is($b->query_safe('SELECT v FROM t'),'10','old snapshot excludes new branch root');
is(sql('SELECT v FROM t'),'10','main remains unchanged');
$b->query_safe('COMMIT');
is($b->query_safe('SELECT v FROM t'),'20','fresh same-branch session sees committed root');
$a->query_safe(q{SELECT dolt_add('.')});
$a->query_safe('UPDATE t SET v=21');
$a->query_safe(q{SELECT dolt_checkout('main')});
is($a->query_safe('EXECUTE read_t(1)'),'10','prepared plan follows session default after checkout');
$a->query_safe(q{SELECT dolt_checkout('feature')});
is($a->query_safe('EXECUTE read_t(1)'),'21','dirty working data survives away-and-back checkout');
$a->query_safe(q{SELECT dolt_commit('-m','staged twenty')});
is($a->query_safe(q{SELECT count(*) FROM dolt_diff_summary('HEAD','WORKING')}),'1','unstaged data remains after branch-local staged commit');
is(sql(q{SELECT count(*) FROM dolt_diff_summary('HEAD','STAGED')}),'0','main staging unaffected');
# Subtransactions restore branch-local roots; prepared data retains branch identity.
$a->query_safe('BEGIN; SAVEPOINT s; UPDATE t SET v=30; ROLLBACK TO s; COMMIT');
is($a->query_safe('SELECT v FROM t'),'21','savepoint rollback restores branch root');
$a->query_safe('BEGIN; UPDATE t SET v=40');
$a->query_safe(q{SELECT dolt_add('.')});
$a->query_safe(q{PREPARE TRANSACTION 'feature_data'});
$a->quit; $b->quit;
$node->stop('immediate');$node->start;
is(sql('SELECT v FROM t'),'10','prepared feature update does not leak to main after restart');
sql(q{COMMIT PREPARED 'feature_data'});
$a=$node->background_psql('postgres');$a->query_safe(q{SELECT dolt_checkout('feature')});
is($a->query_safe('SELECT v FROM t'),'40','prepared branch update publishes after recovery');
is($a->query_safe(q{SELECT count(*) FROM dolt_diff_summary('WORKING','STAGED')}),'0','prepared data and stage publish together');
$a->query_safe(q{SELECT dolt_commit('-m','prepared stage')});
# Merge publication must wait for a table writer, then recheck cleanliness.
$a->query_safe('INSERT INTO t VALUES(2,50)');
$a->query_safe(q{SELECT dolt_commit('-Am','feature insert')});
my $blocker=$node->background_psql('postgres');
$blocker->query_safe('BEGIN; UPDATE t SET v=11 WHERE id=1');
my $merger=$node->background_psql('postgres',on_error_stop=>0);
my $pid=$merger->query_safe('SELECT pg_backend_pid()');
$merger->query_until(qr/start_merge/,q{\echo start_merge
SELECT dolt_merge('feature');
});
ok($node->poll_query_until('postgres',"SELECT wait_event_type='Lock' FROM pg_stat_activity WHERE pid=$pid"),'merge waits for source relation writer');
$blocker->query_safe('COMMIT');
my($out,$err)=$merger->query('SELECT 1');
is($err,1,'merge rejects newly committed dirty destination instead of losing it');
is(sql('SELECT v FROM t WHERE id=1'),'11','concurrent destination write retained');
$merger->quit;$blocker->quit;
sql(q{SELECT dolt_commit('-Am','main changed')});
# Publication cancellation after writing private roots must roll everything back.
my $head=sql(q{SELECT commit_hash FROM dolt_log('-n','1')});
$blocker=$node->background_psql('postgres');
$blocker->query_safe(q{BEGIN; SELECT 1 FROM pg_dolt_ref WHERE refname='working/main' FOR UPDATE});
$merger=$node->background_psql('postgres',on_error_stop=>0);
$pid=$merger->query_safe('SELECT pg_backend_pid()');
$merger->query_until(qr/start_publish/,q{\echo start_publish
SELECT dolt_merge('feature');
});
ok($node->poll_query_until('postgres',"SELECT wait_event_type='Lock' FROM pg_stat_activity WHERE pid=$pid"),'merge reaches blocked ref publication');
is(sql(q{SELECT commit_hash FROM dolt_log('-n','1')}),$head,'private merge HEAD remains invisible');
sql("SELECT pg_cancel_backend($pid)");
($out,$err)=$merger->query('SELECT 1');is($err,1,'publication cancelled');
$blocker->query_safe('ROLLBACK');$blocker->quit;$merger->quit;
is(sql('SELECT * FROM t'),'1|11','cancel restores all live main roots');
is(sql('SELECT is_merging FROM dolt_merge_status'),'f','cancel restores pending metadata');
is(sql(q{SELECT commit_hash FROM dolt_log('-n','1')}),$head,'cancel preserves HEAD');
$a->quit;$node->stop;
done_testing();
