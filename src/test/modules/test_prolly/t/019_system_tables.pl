use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('system_tables');
$node->init(extra=>['--encoding=UTF8','--locale=C']);
$node->append_conf('postgresql.conf',"max_parallel_workers_per_gather=0\n");
$node->start;
sub sql { $node->safe_psql('postgres',$_[0]); }
sql(q{CREATE ROLE reader});
sub fails {
 my($q,$pat,$label)=@_;my($status,$out,$err)=$node->psql('postgres',$q);
 isnt($status,0,$label);like($err,$pat,"$label diagnostic");
}
# Every database starts with an initialized repository whose initial commit records the public schema.
is(sql(q{SELECT name,dirty,latest_commit_message FROM dolt.branches}),'main|f|Initialize data repository','fresh database has main');
is(sql(q{SELECT count(*) FROM dolt.commits}),'1','initial commit visible');
is(sql(q{SELECT parent_hash IS NULL,parent_index FROM dolt.commit_ancestors}),'t|0','root commit ancestor row');
is(sql(q{SELECT count(*) FROM dolt.status}),'0','clean initial status');
is(sql(q{SELECT count(*) FROM dolt.diff}),'0','no table changes in initial state');
# The dolt schema and dolt_ aliases resolve from any schema, but user tables win.
is(sql(q{SELECT name FROM dolt_branches}),'main','pg_catalog alias');
is(sql(q{SELECT name FROM public.dolt_branches}),'main','schema-qualified alias');
is(sql(q{SELECT dolt_branches.name FROM dolt_branches}),'main','alias column qualification');
is(sql(q{SELECT dolt.branches.name FROM dolt.branches}),'main','dolt schema column qualification');
fails(q{SELECT * FROM branches},qr/does not exist/,'unqualified system table name is not implicit');
fails(q{SELECT * FROM public.branches},qr/does not exist/,'public does not contain system tables');
fails(q{SELECT * FROM other.dolt_branches},qr/does not exist/,'alias requires an existing schema');
fails(q{CREATE SCHEMA dolt},qr/already exists/,'dolt schema is reserved');
sql(q{CREATE TABLE branches(id int PRIMARY KEY) USING dolt_prolly_table; INSERT INTO branches VALUES(1)});
is(sql(q{SELECT * FROM branches}),'1','user table shadows nothing');
is(sql(q{SET search_path=dolt; SELECT name FROM branches}),'main','search_path selects dolt schema');
is(sql(q{SET search_path=dolt; SELECT * FROM public.branches}),'1','qualified user table under dolt search_path');
is(sql(q{SET search_path=public,dolt; SELECT * FROM BRANCHES}),'1','user table precedes dolt schema in search_path');
sql(q{CREATE TABLE public.dolt_branches(id int PRIMARY KEY) USING dolt_prolly_table; INSERT INTO public.dolt_branches VALUES(7)});
is(sql(q{SELECT * FROM public.dolt_branches}),'7','user table with alias name wins in its schema');
is(sql(q{SELECT name FROM dolt_branches}),'main','implicit pg_catalog precedes a same-named user table');
is(sql(q{SET search_path=public,pg_catalog; SELECT * FROM dolt_branches}),'7','explicit search_path order selects the user table');
sql(q{DROP TABLE public.dolt_branches});
is(sql(q{SELECT name FROM dolt_branches}),'main','alias restored after drop');
is(sql(q{SET dolt_show_system_tables=1; SHOW dolt_show_system_tables}),'on','dolt_show_system_tables setting');
# Status tracks staged and unstaged tables and schemas.
sql(q{CREATE TABLE t(id int PRIMARY KEY,v text COLLATE "C") USING dolt_prolly_table});
is(sql(q{SELECT * FROM dolt.status ORDER BY table_name}),"public.branches|f|new table\npublic.t|f|new table",'new tables unstaged');
sql(q{CREATE SCHEMA s2});
is(sql(q{SELECT * FROM dolt_status WHERE status LIKE '%schema'}),'s2|f|new schema','new schema unstaged');
sql(q{SELECT dolt_add('.')});
is(sql(q{SELECT count(*) FROM dolt.status WHERE staged}),'3','all staged');
sql(q{INSERT INTO t VALUES(1,'one')});
is(sql(q{SELECT * FROM dolt.status WHERE table_name='public.t' ORDER BY staged}),"public.t|f|modified\npublic.t|t|new table",'staged and unstaged rows for one table');
is(sql(q{SELECT commit_hash,table_name,data_change,schema_change FROM dolt.diff ORDER BY 1,2}),"STAGED|public.branches|t|t\nSTAGED|public.t|f|t\nWORKING|public.t|t|f",'working set rows in dolt_diff');
is(sql(q{SELECT name,dirty FROM dolt.branches}),'main|t','session branch dirty');
my $first=sql(q{SELECT dolt_commit('-Am','first','--author','Author <a@example.com>')});
is(sql(q{SELECT count(*) FROM dolt.status}),'0','clean after commit');
is(sql(q{SELECT name,dirty,latest_commit_message,latest_author,latest_author_email FROM dolt.branches}),'main|f|first|Author|a@example.com','branch metadata follows head');
is(sql(q{SELECT table_name,committer=current_user,message,data_change,schema_change FROM dolt.diff ORDER BY table_name}),"public.branches|t|first|t|t\npublic.t|t|first|t|t",'commit rows in dolt_diff');
is(sql("SELECT commit_hash FROM dolt.diff LIMIT 1"),$first,'dolt_diff reports commit hashes');
is(sql(q{SELECT message FROM dolt.commits}),"first\nInitialize data repository",'commits newest first');
is(sql(q{SELECT count(*) FROM dolt.commit_ancestors WHERE parent_hash IS NOT NULL}),'1','ancestor edge recorded');
is(sql("SELECT parent_hash=(SELECT commit_hash FROM dolt.commits WHERE message='Initialize data repository') FROM dolt.commit_ancestors WHERE commit_hash='$first'"),'t','ancestor points at parent');
sql(q{DROP TABLE branches});
is(sql(q{SELECT * FROM dolt.status}),'public.branches|f|deleted','deleted table status');
is(sql(q{SELECT commit_hash,table_name,data_change,schema_change FROM dolt.diff WHERE commit_hash='WORKING'}),'WORKING|public.branches|t|t','dropped table with rows is a data change');
sql(q{SELECT dolt_commit('-Am','drop')});
sql(q{CREATE TABLE empty_t(id int PRIMARY KEY) USING dolt_prolly_table});
is(sql(q{SELECT commit_hash,table_name,data_change,schema_change FROM dolt.diff WHERE commit_hash='WORKING'}),'WORKING|public.empty_t|f|t','added empty table is only a schema change');
sql(q{SELECT dolt_commit('-Am','empty table')});
# Branch views: aliases keep resolving after checkout, and other branches report persisted dirtiness.
sql(q{SELECT dolt_checkout('-b','feature')});
is(sql(q{SELECT name FROM public.dolt_branches ORDER BY 1}),"feature\nmain",'alias resolution with branch views active');
is(sql(q{SELECT name FROM dolt.branches WHERE name IN ('main')}),'main','IN filter on branches');
my $feature=$node->background_psql('postgres');
$feature->query_safe(q{SELECT dolt_checkout('feature')});
$feature->query_safe(q{INSERT INTO t VALUES(2,'two')});
is($feature->query_safe(q{SELECT name,dirty FROM dolt.branches ORDER BY 1}),"feature|t\nmain|f",'session branch live dirtiness');
is(sql(q{SELECT name,dirty FROM dolt.branches ORDER BY 1}),"feature|f\nmain|f",'other sessions see persisted branch state only');
$feature->query_safe(q{SELECT dolt_add('.')});
is(sql(q{SELECT name,dirty FROM dolt.branches ORDER BY 1}),"feature|t\nmain|f",'staged working set marks branch dirty');
$feature->query_safe(q{SELECT dolt_commit('-m','feature row')});
$feature->quit;
# Merge status and conflicts. Branch selection is per session, so the
# divergent branches are built in one persistent session.
my $s=$node->background_psql('postgres');
$s->query_safe(q{SELECT dolt_branch('x1')});
$s->query_safe(q{SELECT dolt_checkout('-b','x2')});
$s->query_safe(q{INSERT INTO t VALUES(3,'x2')});
$s->query_safe(q{SELECT dolt_commit('-Am','x2')});
$s->query_safe(q{SELECT dolt_checkout('x1')});
$s->query_safe(q{INSERT INTO t VALUES(3,'x1')});
$s->query_safe(q{SELECT dolt_commit('-Am','x1')});
$s->query_safe(q{SELECT dolt_checkout('main')});
$s->quit;
is(sql(q{SELECT * FROM dolt.merge_status}),'f||||','no merge in progress');
sql(q{SELECT dolt_merge('x1')});
is(sql(q{SELECT conflicts FROM dolt_merge('x2')}),'1','conflicting merge');
my $x2=sql(q{SELECT commit_hash FROM dolt_log('x2','-n','1')});
is(sql(q{SELECT is_merging,source,source_commit,target,unmerged_tables FROM dolt.merge_status}),"t|x2|$x2|refs/heads/main|t",'merge status describes the pending merge');
is(sql(q{SELECT * FROM dolt.conflicts}),'t|1','conflict summary uses unqualified table name');
is(sql(q{SELECT * FROM dolt_conflicts}),'t|1','conflict alias');
is(sql(q{SELECT * FROM dolt.status}),'public.t|f|conflict','conflict status');
sql(q{SELECT dolt_conflicts_resolve('--ours','t')});
is(sql(q{SELECT is_merging,unmerged_tables FROM dolt_merge_status}),'t|','resolved conflicts leave merge pending');
sql(q{SELECT dolt_commit('-m','merged x2')});
is(sql(q{SELECT is_merging FROM dolt.merge_status}),'f','commit finishes merge');
# Remotes and docs are database-local configuration.
is(sql(q{SELECT dolt_remote('add','origin','https://example.com/org/repo')}),'0','remote added');
is(sql(q{SELECT name,url,fetch_specs::text FROM dolt.remotes}),'origin|https://example.com/org/repo|["refs/heads/*:refs/remotes/origin/*"]','remote row');
is(sql(q{SELECT name FROM dolt_remotes}),'origin','remotes alias');
is(sql(q{SELECT count(*) FROM dolt.remote_branches}),'0','no remote branches before fetch');
fails(q{SELECT dolt_remote('add','origin','x')},qr/already exists/,'duplicate remote');
is(sql(q{SELECT dolt_remote('remove','origin')}),'0','remote removed');
is(sql(q{SELECT count(*) FROM dolt.remotes}),'0','remote gone');
is(sql(q{SELECT doc_name,length(doc_text)>100 FROM dolt.docs}),'AGENT.md|t','default agent document');
sql(q{INSERT INTO dolt.docs VALUES('README.md','testing')});
is(sql(q{SELECT doc_name FROM dolt_docs ORDER BY 1}),"AGENT.md\nREADME.md",'inserted document through alias');
sql(q{UPDATE dolt_docs SET doc_text='updated' WHERE doc_name='README.md'});
is(sql(q{SELECT doc_text FROM public.dolt_docs WHERE doc_name='README.md'}),'updated','document updated');
sql(q{DELETE FROM dolt.docs WHERE doc_name='README.md'});
is(sql(q{SELECT count(*) FROM dolt.docs}),'1','document deleted');
is(sql(q{SELECT count(*) FROM dolt.status}),'0','dolt schema objects are not versioned');
# Tags and log keep their aliases.
sql(q{SELECT dolt_tag('v1')});
is(sql(q{SELECT tag_name FROM dolt.tags}),'v1','tags in dolt schema');
is(sql(q{SELECT tag_name FROM public.dolt_tags}),'v1','tags alias');
is(sql(q{SELECT count(*) FROM dolt.log}),sql(q{SELECT count(*) FROM dolt_log}),'log alias');
fails(q{SET ROLE reader; SELECT * FROM dolt.branches},qr/permission denied/,'system tables remain privileged');
$node->stop;
done_testing();
