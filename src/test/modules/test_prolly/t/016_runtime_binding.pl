use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('runtime_binding');
$node->init(allows_streaming=>1,extra=>['--encoding=UTF8','--locale=C']);
$node->start;
sub sql { return $node->safe_psql('postgres',$_[0]); }
sub fails { my($q,$pattern,$label)=@_;my($s,$o,$e)=$node->psql('postgres',$q);isnt($s,0,$label);like($e,$pattern,"$label diagnostic"); }
sql(q{CREATE ROLE reader; CREATE TABLE t(id int PRIMARY KEY,v text) USING dolt_prolly_table; INSERT INTO t VALUES(1,'base'); GRANT SELECT ON t TO reader});
my $commit=sql(q{SELECT dolt_commit('-Am','base')});
my $oid=sql(q{SELECT 't'::regclass::oid});
is(sql(q{SELECT count(*) FROM pg_dolt_binding WHERE bindbranch='main'}),'2','capture registers table and index runtime bindings');
is(sql(q{SELECT bool_and(o.objkind='schema') FROM pg_dolt_binding b JOIN pg_dolt_object o ON o.objhash=b.bindschema}),'t','bindings refer to canonical schema objects');
sql(q{SELECT dolt_branch('other'); SELECT dolt_checkout('other')});
is(sql(q{SELECT count(*) FROM pg_dolt_binding WHERE bindbranch='other'}),'2','branch administration initializes local bindings');
is(sql(q{SELECT count(*) FROM pg_dolt_binding a JOIN pg_dolt_binding b USING(bindname) WHERE a.bindbranch='main' AND b.bindbranch='other' AND a.bindrelid=b.bindrelid AND a.bindschema=b.bindschema}),'2','compatible branches share runtime resources without a catalog copy');
is(sql(q{SET ROLE reader; BEGIN READ ONLY; SELECT * FROM "postgres/other".public.t; SELECT pg_current_xact_id_if_assigned() IS NULL; COMMIT}),"1|base\nt",'ordinary read-only binding needs no writes or caller elevation');
fails(q{SET ROLE reader; SELECT * FROM pg_dolt_binding},qr/permission denied/,'runtime mappings are not public SQL data');
is(sql(q{SELECT count(*) FROM dolt_diff_summary('HEAD','WORKING')}),'0','local binding publication does not change canonical database content');
my $plan=$node->background_psql('postgres',on_error_stop=>0);
$plan->query_safe('PREPARE binding_plan AS SELECT * FROM t WHERE false');
my $old=$node->background_psql('postgres');
$old->query_safe('BEGIN ISOLATION LEVEL REPEATABLE READ; SELECT count(*) FROM pg_class');
# Superuser fault injection into local metadata: prove MVCC and fail-closed reads.
# This is test-only; no public mapping mutation API is introduced.
sql(q{UPDATE pg_dolt_binding SET bindschema=decode(repeat('00',32),'hex') WHERE bindbranch='main' AND bindname='public.t'});
my($planout,$planerr)=$plan->query('EXECUTE binding_plan');
is($planerr,1,'prepared zero-row plan revalidates the runtime binding');$plan->quit;
is($old->query_safe('SELECT * FROM t'),'1|base','old snapshot retains its binding generation');
$old->query_safe('COMMIT');$old->quit;
fails('SELECT * FROM t',qr/runtime catalog binding (mismatch|unavailable)/,'fresh ordinary read rejects stale schema binding');
fails(q{SELECT * FROM "postgres/main".public.t},qr/runtime catalog binding unavailable/,'qualified working read rejects stale schema binding');
is(sql("SELECT * FROM t AS OF '$commit'"),'1|base','historical read is independent of local runtime mapping');
sql(q{UPDATE pg_dolt_binding a SET bindschema=b.bindschema FROM pg_dolt_binding b WHERE a.bindbranch='main' AND a.bindname='public.t' AND b.bindbranch='other' AND b.bindname=a.bindname});
is(sql('SELECT * FROM t'),'1|base','restored mapping resumes ordinary reads');
fails(q{BEGIN; UPDATE pg_dolt_binding SET bindrelid=0 WHERE bindbranch='main' AND bindname='public.t'; INSERT INTO t VALUES(2,'wrong')},qr/runtime catalog binding (mismatch|unavailable)/,'write rejects wrong physical generation');
is(sql('SELECT count(*) FROM t'),'1','failed binding write has no data effect');
sql(q{BEGIN; CREATE TABLE aborted(id int); ROLLBACK});
is(sql(q{SELECT count(*) FROM pg_dolt_binding WHERE bindname='public.aborted'}),'0','aborted CREATE rolls back local binding');
sql(q{BEGIN; SAVEPOINT s; CREATE TABLE rolled(id int); ROLLBACK TO s; COMMIT});
is(sql(q{SELECT count(*) FROM pg_dolt_binding WHERE bindname='public.rolled'}),'0','savepoint rollback removes local binding');
sql(q{DELETE FROM pg_dolt_binding WHERE bindbranch='main' AND bindname='public.t'});
fails(q{BEGIN READ ONLY; SELECT * FROM "postgres/main".public.t},qr/runtime catalog binding unavailable/,'read-only query does not silently repair missing mapping');
is(sql(q{SELECT count(*) FROM pg_dolt_binding WHERE bindbranch='main' AND bindname='public.t'}),'0','failed read leaves local mapping absent');
sql(q{SELECT dolt_checkout('main')});
is(sql(q{SELECT * FROM "postgres/main".public.t}),'1|base','explicit branch administration reuses unambiguous captured binding');
my $schema=sql(q{SELECT encode(bindschema,'hex') FROM pg_dolt_binding WHERE bindbranch='main' AND bindname='public.t'});
$node->stop('immediate');$node->start;
is(sql('SELECT * FROM "postgres/other".public.t'),'1|base','branch binding survives recovery');
is(sql(q{SELECT bindrelid FROM pg_dolt_binding WHERE bindbranch='main' AND bindname='public.t'}),$oid,'runtime OID mapping survives restart');
is(sql(q{SELECT encode(bindschema,'hex') FROM pg_dolt_binding WHERE bindbranch='main' AND bindname='public.t'}),$schema,'schema binding survives restart');
$node->backup('bound');
my $standby=PostgreSQL::Test::Cluster->new('bound_standby');
$standby->init_from_backup($node,'bound',has_streaming=>1);$standby->start;
is($standby->safe_psql('postgres',q{SET ROLE reader; SELECT * FROM "postgres/other".public.t; SELECT pg_current_xact_id_if_assigned() IS NULL}),"1|base\nt",'cold standby working query uses WAL-recovered binding without writes');
$standby->stop;
my $pending=$node->background_psql('postgres');
$pending->query_safe(q{BEGIN; CREATE TABLE pending(id int PRIMARY KEY); INSERT INTO pending VALUES(9)});
is(sql(q{SELECT count(*) FROM pg_dolt_binding WHERE bindname IN ('public.pending','public.pending_pkey')}),'0','uncommitted bindings invisible to another session');
$node->stop('immediate');$pending->quit;$node->start;
is(sql(q{SELECT count(*) FROM pg_dolt_binding WHERE bindname IN ('public.pending','public.pending_pkey')}),'0','crash rolls back table and index mappings');
is(sql(q{SELECT to_regclass('pending') IS NULL}),'t','crash also rolls back corresponding runtime relation');
$node->stop;done_testing();
