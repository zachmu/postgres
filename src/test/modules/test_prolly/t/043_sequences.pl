# Definitions belong to branches; the native WAL-backed allocator is shared.
use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node = PostgreSQL::Test::Cluster->new('sequences');
$node->init;
$node->append_conf('postgresql.conf', "default_table_access_method='dolt_prolly_table'\n");
$node->start;
my $a=$node->background_psql('postgres',on_error_stop=>0);
my $b=$node->background_psql('postgres',on_error_stop=>0);
sub sql { $a->query_safe($_[0]); }
sub fails { my ($q,$re,$label)=@_; $a->query($q); like($a->{stderr},$re,$label); $a->{stderr}=''; }
sql(q{CREATE SEQUENCE s START 10});
is(sql(q{SELECT nextval('s')}),'10','native sequence allocation starts at the declared value');
is(sql(q{SELECT table_name FROM dolt_status}),'public.s','sequence membership appears in status');
is(sql(q{SELECT seqstart FROM pg_sequence WHERE seqrelid='s'::regclass}),'10','pg_sequence reads the branch definition');
fails(q{CREATE SEQUENCE s},qr/already exists/,'duplicate sequence names are rejected');
sql(q{SELECT dolt_commit('-Am','sequence')});
sql(q{SELECT dolt_branch('other')});
is(sql(q{SELECT last_value,is_called FROM s AS OF 'HEAD'}),'10|t','historical sequence scans read the committed snapshot');
is(sql(q{SELECT setval('s',20)}),'20','setval updates the shared allocator');
$b->query_safe(q{SELECT dolt_checkout('other')});
is($b->query_safe(q{SELECT nextval('s')}),'21','another branch advances the same allocator');
$b->query_safe(q{SELECT dolt_reset('--hard')});
is($b->query_safe(q{SELECT nextval('s')}),'22','reset does not rewind allocation');
$b->query_safe(q{DROP SEQUENCE s});
is($b->query_safe(q{SELECT count(*) FROM pg_sequence}),'0','drop removes only that branch definition');
is(sql(q{SELECT last_value FROM s}),'22','working sequence scans read shared allocation');
is(sql(q{SELECT nextval('s')}),'23','the original branch still uses its sequence');
$b->query_safe(q{CREATE SEQUENCE s START 100});
is($b->query_safe(q{SELECT seqstart FROM pg_sequence WHERE seqrelid='s'::regclass}),'100','same name can have another definition');
is(sql(q{SELECT seqstart FROM pg_sequence WHERE seqrelid='s'::regclass}),'10','the original definition is unchanged');
is(sql(q{SELECT count(*) FROM pg_dolt_sequence}),'1','both definitions have one allocator record');
sql(q{CREATE TABLE t(id serial PRIMARY KEY,v int)});
sql(q{INSERT INTO t(v) VALUES(1)});
is(sql(q{SELECT id FROM t}),'1','SERIAL resolves its versioned sequence');
sql(q{SELECT dolt_add('t')});
is(sql(q{SELECT count(*) FROM dolt_status WHERE staged AND table_name IN ('public.t','public.t_id_seq')}),'2','staging a table includes its owned sequence');
sql(q{DROP TABLE t});
fails(q{SELECT nextval('t_id_seq')},qr/does not exist/,'dropping the owning table drops the branch sequence');
sql(q{CREATE TABLE ident(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)});
sql(q{INSERT INTO ident DEFAULT VALUES});
is(sql(q{SELECT id FROM ident}),'1','identity columns resolve a single ownership edge');
fails(q{DROP SEQUENCE ident_id_seq},qr/requires it|depends on it/,'an identity sequence cannot be dropped independently');
sql(q{ALTER TABLE ident ALTER COLUMN id DROP IDENTITY});
fails(q{SELECT nextval('ident_id_seq')},qr/does not exist/,'DROP IDENTITY removes the branch sequence definition');
sql(q{CREATE TABLE added(id int NOT NULL)});
sql(q{ALTER TABLE added ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START 7)});
sql(q{INSERT INTO added DEFAULT VALUES});
is(sql(q{SELECT id FROM added}),'7','ALTER TABLE can publish a new identity sequence');
sql(q{CREATE SEQUENCE owned});
sql(q{ALTER SEQUENCE owned OWNED BY added.id});
sql(q{DROP TABLE added});
fails(q{SELECT nextval('owned')},qr/does not exist/,'ALTER SEQUENCE ownership participates in branch DROP');
# Distinct names on different branches do not serialize DDL on the allocator catalog.
sql(q{BEGIN; CREATE SEQUENCE main_only});
$b->query_safe(q{SET statement_timeout='3s'; CREATE SEQUENCE other_only});
sql('COMMIT');
is(sql(q{SELECT count(*) FROM pg_class WHERE relname='other_only'}),'0','parallel branch CREATE remains isolated');
# Definition publication rolls back; allocation deliberately does not.
sql(q{BEGIN; CREATE SEQUENCE rolled_back; ROLLBACK});
fails(q{SELECT nextval('rolled_back')},qr/does not exist/,'aborted CREATE publishes no definition');
sql(q{BEGIN; SELECT nextval('s'); ROLLBACK});
is(sql(q{SELECT nextval('s')}),'25','aborted SQL transactions do not rewind allocation');
fails(q{ALTER SEQUENCE s INCREMENT 2},qr/unsupported/,'unimplemented ALTER cannot mutate the shared allocator');
is(sql(q{SELECT seqincrement FROM pg_sequence WHERE seqrelid='s'::regclass}),'1','rejected ALTER leaves the definition unchanged');
# Ordinary object merging carries sequence definitions into the destination.
sql(q{SELECT dolt_commit('-Am','main sequences')});
sql(q{SELECT dolt_branch('merge_sequences')});
$b->query_safe(q{SELECT dolt_checkout('merge_sequences')});
$b->query_safe(q{CREATE SEQUENCE merged_seq START 70});
$b->query_safe(q{SELECT dolt_commit('-Am','added sequence')});
sql(q{CREATE SEQUENCE independent_seq});
sql(q{SELECT dolt_commit('-Am','independent sequence')});
is(sql(q{SELECT conflicts FROM dolt_merge('merge_sequences')}),'0','disjoint sequence definitions merge');
is(sql(q{SELECT nextval('merged_seq')}),'70','merged sequence binds the shared allocator');
is($b->query_safe(q{SELECT nextval('merged_seq')}),'71','source and destination keep sharing allocation after merge');
$a->quit;
$b->quit;
$node->stop('immediate');
$node->start;
cmp_ok($node->safe_psql('postgres',q{SELECT nextval('s')}),'>=',26,'WAL recovery preserves the allocation high-water mark');
$node->stop;
done_testing();
