use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('same_name');
$node->init(allows_streaming=>1,extra=>['--encoding=UTF8','--locale=C']);
$node->start;
sub sql { return $node->safe_psql('postgres',$_[0]); }
sub fails { my($q,$pattern,$label)=@_;my($s,$o,$e)=$node->psql('postgres',$q);isnt($s,0,$label);like($e,$pattern,"$label diagnostic"); }
sql(q{CREATE TABLE seed(id int) USING dolt_prolly_table; SELECT dolt_commit('-Am','base'); SELECT dolt_branch('other'); SELECT dolt_checkout('other')});
sql(q{CREATE TABLE t(id int PRIMARY KEY,v int UNIQUE); INSERT INTO t VALUES(1,10)});
is(sql('SELECT * FROM t'),'1|10','main logical name binds its runtime generation');
my $mainoid=sql(q{SELECT 't'::regclass::oid});
my $main=sql(q{SELECT dolt_commit('-Am','main table')});
my $other=$node->background_psql('postgres');
$other->query_safe(q{SELECT dolt_checkout('other')});
$other->query_safe(q{CREATE TABLE t(id int PRIMARY KEY,v text UNIQUE,note text); INSERT INTO t VALUES(1,'ten','other')});
is($other->query_safe('SELECT * FROM t'),'1|ten|other','same name with incompatible definition works on other branch');
isnt($other->query_safe(q{SELECT 't'::regclass::oid}),$mainoid,'incompatible writable definitions have distinct runtime OIDs');
is(sql('SELECT a.v,b.v,b.note FROM "postgres/main".public.t a JOIN "postgres/other".public.t b USING(id)'),'10|ten|other','one query binds incompatible working schemas');
$other->query_safe(q{UPDATE t SET note='changed'; INSERT INTO t VALUES(2,'two','added'); DELETE FROM t WHERE id=2});
is(sql('SELECT * FROM t'),'1|10','other branch INSERT UPDATE DELETE do not affect main');
my $copyfile = PostgreSQL::Test::Utils::tempdir . '/rows.txt';
append_to_file($copyfile, "3\tthree\tcopy\n");
$other->query_safe("COPY t(id,v,note) FROM '$copyfile'");
is($other->query_safe(q{SELECT v FROM t WHERE id=3}),'three','COPY FROM uses bound runtime table');
my $othercommit=$other->query_safe(q{SELECT dolt_commit('-Am','other table')});
is(sql("SELECT a.v,b.v,b.note FROM t AS OF '$main' a JOIN t AS OF '$othercommit' b USING(id)"),'10|ten|changed','committed incompatible schemas remain independently readable');
sql(q{CREATE TABLE IF NOT EXISTS t(wrong text)});
is(sql('SELECT * FROM t'),'1|10','IF NOT EXISTS tests logical selected-branch membership');
fails(q{CREATE TABLE t(id int)},qr/already exists/,'duplicate CREATE on same branch rejected');
my $internal=sql(q{SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE c.oid='t'::regclass});
fails("SELECT * FROM $internal.t",qr/private runtime/,'direct internal namespace access rejected');
is(sql(q{SELECT count(*) FROM pg_dolt_object WHERE objkind IN ('schema','namespace','table','index','database') AND position('pg_dolt_runtime_'::bytea in objpayload)>0}),'0','manifest envelopes and descriptors exclude internal namespace names');
my $schema=sql(q{SELECT encode(bindschema,'hex') FROM pg_dolt_binding WHERE bindbranch='main' AND bindname='public.t'});
sql(q{DROP TABLE t; CREATE TABLE t(id int PRIMARY KEY,v int UNIQUE); INSERT INTO t VALUES(1,10); SELECT dolt_commit('--allow-empty','-Am','recreated')});
isnt(sql(q{SELECT 't'::regclass::oid}),$mainoid,'DROP recreate allocates a fresh runtime generation');
is(sql(q{SELECT encode(bindschema,'hex') FROM pg_dolt_binding WHERE bindbranch='main' AND bindname='public.t'}),$schema,'canonical schema identity excludes runtime allocation and namespace');
is($other->query_safe('SELECT v FROM t WHERE id=1'),'ten','DROP recreate on main preserves other branch');
sql(q{BEGIN; DROP TABLE t; CREATE TABLE t(id int,v text); INSERT INTO t VALUES(1,'abort'); ROLLBACK});
is(sql('SELECT * FROM t'),'1|10','abort restores old membership and runtime generation');

# Identical schemas are compatible runtime resources, not shared branch contents.
sql(q{CREATE TABLE identical(id int PRIMARY KEY,v text UNIQUE); INSERT INTO identical VALUES(1,'main'); SELECT dolt_commit('-Am','main identical')});
$other->query_safe(q{CREATE TABLE identical(id int PRIMARY KEY,v text UNIQUE); INSERT INTO identical VALUES(2,'other'); SELECT dolt_commit('-Am','other identical')});
is(sql(q{SELECT count(DISTINCT encode(bindschema,'hex')) FROM pg_dolt_binding WHERE bindname='public.identical'}),'1','independently allocated tables have identical canonical schemas');
$other->query_safe(q{SELECT dolt_branch('cloneother')});
my $clone=$node->background_psql('postgres');
$clone->query_safe(q{SELECT dolt_checkout('cloneother')});
is($clone->query_safe('SELECT * FROM identical'),'2|other','clone bootstraps selected HEAD despite multiple compatible runtime generations');
$clone->query_safe(q{INSERT INTO identical VALUES(3,'clone'); SELECT dolt_commit('-Am','clone writes')});
is($other->query_safe('SELECT * FROM identical'),'2|other','clone writes preserve source contents');
is(sql('SELECT * FROM identical'),'1|main','clone writes preserve other compatible runtime generation');
$clone->quit;
sql(q{SELECT dolt_checkout('-b','clonemain','main'); INSERT INTO identical VALUES(4,'mainclone'); SELECT dolt_commit('-Am','mainclone writes')});
is(sql('SELECT * FROM identical'),'1|main','checkout -b initializes independent roots too');
# Index names share the logical relation namespace even across private slots.
sql(q{CREATE TABLE collision_pkey(id int); CREATE TABLE collision(id int PRIMARY KEY)});
is(sql(q{SELECT count(*) FROM pg_dolt_binding WHERE bindbranch='main' AND bindname='public.collision_pkey1'}),'1','automatic index naming avoids logical table collision');
fails(q{CREATE TABLE failed(id int CONSTRAINT identical_pkey PRIMARY KEY)},qr/already exists/,'explicit duplicate logical index name rejected');
is(sql(q{SELECT to_regclass('failed') IS NULL}),'t','index collision rolls back table and namespace allocation');
fails(q{CREATE TABLE identical_pkey(id int)},qr/already exists/,'table name cannot shadow logical index');
# Explicit transactions and savepoints publish all local catalog resources atomically.
sql(q{BEGIN; SAVEPOINT s; DROP TABLE identical; CREATE TABLE identical(wrong text); ROLLBACK TO s; INSERT INTO identical VALUES(5,'saved'); COMMIT});
is(sql('SELECT * FROM identical ORDER BY id'),"1|main\n5|saved",'savepoint restores prior binding for later writes');
$other->quit;
$node->stop('immediate');$node->start;
is(sql('SELECT * FROM t'),'1|10','main generation survives recovery');
is(sql('SELECT v,note FROM "postgres/other".public.t WHERE id=1'),'ten|changed','other generation survives recovery');
$node->backup('same_name');my $standby=PostgreSQL::Test::Cluster->new('standby');
$standby->init_from_backup($node,'same_name',has_streaming=>1);$standby->start;
is($standby->safe_psql('postgres','SELECT a.v,b.v FROM "postgres/main".public.t a JOIN "postgres/other".public.t b USING(id)'),'10|ten','cold standby joins both mapped generations without preparation');
$standby->stop;$node->stop;done_testing();
