use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('merge');
$node->init(extra=>['--encoding=UTF8','--locale=C']);
$node->append_conf('postgresql.conf',"max_parallel_workers_per_gather=0\nmax_prepared_transactions=10\n");
$node->start;
sub sql { $node->safe_psql('postgres',$_[0]); }
sub fails { my($q,$pat,$why)=@_; my($status,$out,$err)=$node->psql('postgres',$q); isnt($status,0,$why); like($err,$pat,"$why diagnostic"); }
sql(q{CREATE TABLE t(id int PRIMARY KEY,a int,b int) USING dolt_prolly_table; CREATE TABLE bag(v text COLLATE "C") USING dolt_prolly_table; CREATE TABLE u(id int PRIMARY KEY,v int UNIQUE) USING dolt_prolly_table; INSERT INTO t VALUES(1,10,20); INSERT INTO bag VALUES('x'); INSERT INTO u VALUES(1,10)});
sql(q{SELECT dolt_commit('-Am','base')});
sql(q{SELECT dolt_branch('feature')});
my $other=$node->background_psql('postgres');
$other->query_safe(q{SELECT dolt_checkout('feature')});
is($other->query_safe('SELECT active_branch()'),'feature','checkout sets session branch');
is(sql('SELECT active_branch()'),'main','other session keeps its branch');
is($other->query_safe('SELECT * FROM t'),'1|10|20','branch starts from retained commit');
$other->query_safe('UPDATE t SET a=11 WHERE id=1');
is(sql('SELECT a FROM t'),'10','branch update isolated');
is($other->query_safe('SELECT a FROM t'),'11','own branch update visible');
$other->query_safe(q{INSERT INTO bag VALUES('x')});
$other->query_safe(q{SELECT dolt_commit('-am','feature')});
sql(q{UPDATE t SET b=21 WHERE id=1; INSERT INTO t VALUES(2,30,40); INSERT INTO bag VALUES('x')});
sql(q{SELECT dolt_commit('-Am','main')});
is(sql(q{SELECT fast_forward,conflicts,message FROM dolt_merge('feature')}),'0|0|merge successful','divergent clean merge');
is(sql('SELECT * FROM t ORDER BY id'),"1|11|21\n2|30|40",'independent columns and insert combined');
is(sql('SELECT count(*) FROM bag'),'3','keyless identical inserts add occurrences');
is($other->query_safe('SELECT * FROM t'),'1|11|20','merge does not change source branch');
is(sql(q{SELECT array_length(string_to_array(parents,', '),1) FROM dolt_log('--parents','-n','1')}),'2','merge commit retains two parents');
is(sql(q{SELECT conflicts,message FROM dolt_merge('feature')}),'0|Already up to date.','repeat merge no-op');
# Index paths carry the selected branch just like sequential scans.
$other->query_safe('SET enable_seqscan=off');
is($other->query_safe('SELECT a,b FROM t WHERE id=1'),'11|20','branch index fetch selects matching table state');
fails('ALTER TABLE t ADD COLUMN c int',qr/schema changes/,'shared schema changes rejected after checkout');
fails(q{BEGIN; SELECT dolt_merge('feature')},qr/transaction block/,'merge outside explicit transaction');
# Clean fast-forward and forced merge.
sql(q{SELECT dolt_branch('ff')});
$other->query_safe(q{SELECT dolt_checkout('ff')});
$other->query_safe('INSERT INTO t VALUES(3,50,60)');
$other->query_safe(q{SELECT dolt_commit('-Am','ff')});
is(sql(q{SELECT fast_forward,conflicts FROM dolt_merge('ff')}),'1|0','fast-forward updates destination data');
is(sql('SELECT count(*) FROM t'),'3','fast-forward installs data');
sql(q{SELECT dolt_branch('forced')});
$other->query_safe(q{SELECT dolt_checkout('forced')});
$other->query_safe('INSERT INTO t VALUES(4,70,80)');
$other->query_safe(q{SELECT dolt_commit('-Am','forced')});
is(sql(q{SELECT fast_forward,conflicts FROM dolt_merge('forced','--no-ff','-m','forced merge')}),'0|0','no-ff creates merge commit');
is(sql(q{SELECT message FROM dolt_log('-n','1')}),'forced merge','merge message');
# Conflicts persist, while SQL remains usable. Restart must not lose them.
sql(q{SELECT dolt_branch('conflicting')});
$other->query_safe(q{SELECT dolt_checkout('conflicting')});
$other->query_safe('UPDATE t SET a=100 WHERE id=1');
$other->query_safe(q{SELECT dolt_commit('-Am','theirs')});
sql('UPDATE t SET a=200 WHERE id=1');
sql(q{SELECT dolt_commit('-Am','ours')});
is(sql(q{SELECT conflicts FROM dolt_merge('conflicting')}),'1','row conflict returned without error');
is(sql('SELECT 1'),'1','connection usable after merge conflict');
is(sql('SELECT a FROM t WHERE id=1'),'200','ours remains visible for conflicting row');
is(sql('SELECT * FROM dolt_conflicts'),'public.t|1','durable conflict summary');
is(sql(q{SELECT base IS NOT NULL,ours IS NOT NULL,theirs IS NOT NULL FROM dolt_conflict_rows('t')}),'t|t|t','all three conflict values retained');
fails(q{SELECT dolt_commit('-Am','unresolved')},qr/unresolved merge conflicts/,'unresolved conflicts prevent commit');
$other->quit;
$node->stop('immediate'); $node->start;
is(sql('SELECT * FROM dolt_conflicts'),'public.t|1','conflict survives crash');
is(sql('SELECT is_merging FROM dolt_merge_status'),'t','merge pending after crash');
sql(q{SELECT dolt_conflicts_resolve('--theirs','t')});
is(sql('SELECT a FROM t WHERE id=1'),'100','theirs resolution installed');
is(sql('SELECT count(*) FROM dolt_conflicts'),'0','resolved evidence removed');
sql(q{SELECT dolt_commit('-Am','resolved')});
is(sql('SELECT is_merging FROM dolt_merge_status'),'f','commit clears pending merge');
is(sql(q{SELECT array_length(string_to_array(parents,', '),1) FROM dolt_log('--parents','-n','1')}),'2','resolved commit has both parents');
# Another conflict can be aborted atomically.
sql(q{SELECT dolt_branch('abort_case')});
$other=$node->background_psql('postgres');
$other->query_safe(q{SELECT dolt_checkout('abort_case')});
$other->query_safe('DELETE FROM t WHERE id=1');
$other->query_safe(q{SELECT dolt_commit('-Am','delete')});
sql('UPDATE t SET b=999 WHERE id=1');sql(q{SELECT dolt_commit('-Am','update')});
is(sql(q{SELECT conflicts FROM dolt_merge('abort_case')}),'1','delete/update conflicts');
is(sql(q{SELECT message FROM dolt_merge('--abort')}),'merge aborted','abort succeeds');
is(sql('SELECT a,b FROM t WHERE id=1'),'100|999','abort restores original destination');
is(sql('SELECT count(*) FROM dolt_conflicts'),'0','abort clears conflicts');
# Secondary unique collisions are conflicts rather than an aborting index error.
sql(q{SELECT dolt_branch('unique_case')});
$other->query_safe(q{SELECT dolt_checkout('unique_case')});
$other->query_safe('INSERT INTO u VALUES(2,20)');
$other->query_safe(q{SELECT dolt_commit('-Am','unique theirs')});
sql('INSERT INTO u VALUES(3,20)');sql(q{SELECT dolt_commit('-Am','unique ours')});
is(sql(q{SELECT conflicts FROM dolt_merge('unique_case')}),'1','unique conflict is non-aborting');
is(sql(q{SELECT whole_table FROM dolt_conflict_rows('u')}),'t','unique conflict explicitly records whole-table granularity');
sql(q{SELECT dolt_conflicts_resolve('--ours','.')});sql(q{SELECT dolt_commit('-Am','unique resolved')});
is(sql('SELECT * FROM u ORDER BY id'),"1|10\n3|20",'ours unique table preserved');
$other->quit;
$node->stop;
done_testing();
