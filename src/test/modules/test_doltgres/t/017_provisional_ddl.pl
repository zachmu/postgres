use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('provisional_ddl');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->start;
my $s=$node->background_psql('postgres',on_error_stop=>0);
sub sql {return $s->query_safe($_[0]);}
sub rejects {my ($out,$failed)=$s->query($_[0]);is($failed,1,$_[1]);$s->{stderr}='';}
sql(q{SET statement_timeout='10s'; SET client_min_messages=warning;
CREATE TABLE t(id int PRIMARY KEY,x int,payload text) USING dolt_prolly_table;
INSERT INTO t VALUES(1,1,'a'),(2,NULL,'b');
SELECT dolt_commit('-Am','base'); SELECT dolt_checkout('-b','other')});
rejects(q{ALTER TABLE t ALTER COLUMN x SET NOT NULL},'native validation scan rejects existing nulls');
is(sql(q{SELECT attnotnull FROM pg_attribute WHERE attrelid='t'::regclass AND attname='x'}),'f','failed scan leaves original definition');
sql(q{UPDATE t SET x=2 WHERE id=2});
sql(q{ALTER TABLE t ALTER COLUMN x SET NOT NULL, ALTER COLUMN x SET STATISTICS 50, ALTER COLUMN payload SET STORAGE MAIN});
is(sql(q{SELECT attnotnull,attstattarget FROM pg_attribute WHERE attrelid='t'::regclass AND attname='x'}),'t|50','native multi-pass ALTER publishes staged constraint and attribute changes');
rejects(q{INSERT INTO t VALUES(3,NULL,'c')},'new constraint enforced on writes');
is(sql(q{SELECT count(*) FROM pg_constraint WHERE conrelid='t'::regclass AND contype='n'}),'2','native constraint insert is present in canonical catalog');
rejects(q{ALTER TABLE t ALTER COLUMN id DROP NOT NULL},'native primary-key dependency protects NOT NULL');
sql(q{BEGIN; SAVEPOINT before_drop; ALTER TABLE t ALTER COLUMN x DROP NOT NULL});
is(sql(q{SELECT attnotnull FROM pg_attribute WHERE attrelid='t'::regclass AND attname='x'}),'f','native deletion changes constraint and attribute together');
sql(q{ROLLBACK TO before_drop});
is(sql(q{SELECT attnotnull FROM pg_attribute WHERE attrelid='t'::regclass AND attname='x'}),'t','savepoint restores complete schema publication');
sql(q{COMMIT});
my $main=$node->background_psql('postgres');
$main->query_safe(q{SET statement_timeout='2s'; PREPARE untouched AS SELECT count(*) FROM t WHERE x IS NULL; BEGIN; UPDATE t SET payload='main' WHERE id=1});
sql(q{BEGIN; ALTER TABLE t ALTER COLUMN x DROP NOT NULL; INSERT INTO t VALUES(3,NULL,'c'); COMMIT});
is($main->query_safe('EXECUTE untouched'),'1','other branch keeps its prepared view while writes overlap');
$main->query_safe('COMMIT');$main->quit;
is(sql(q{SELECT count(*) FROM pg_constraint WHERE conrelid='t'::regclass AND contype='n'}),'1','native constraint deletion retained');
is(sql(q{SELECT attnotnull FROM pg_attribute AS OF 'main' WHERE attname='x'}),'f','other branch catalog remains independent');
sql(q{SELECT dolt_commit('-Am','native constraints')});
$s->quit;$node->restart;
$s=$node->background_psql('postgres',on_error_stop=>0);sql(q{SELECT dolt_checkout('other')});
is(sql(q{SELECT count(*) FROM t}),'3','native DDL and data survive restart');
sql(q{SET client_min_messages=warning; ALTER TABLE t ADD COLUMN extra text, ALTER COLUMN extra SET STORAGE MAIN, ALTER COLUMN id SET STATISTICS 70});
is(sql(q{SELECT id,x,payload,extra FROM t ORDER BY id}),"1|1|a|\n2|2|b|\n3||c|",'native ADD COLUMN pads stored tuples and subsequent passes reopen it');
rejects(q{ALTER TABLE t ADD COLUMN impossible int, ALTER COLUMN impossible SET NOT NULL},'native scan sees NULL in newly staged column');
is(sql(q{SELECT count(*) FROM pg_attribute WHERE attrelid='t'::regclass AND attname='impossible'}),'0','failed added-column validation is atomic');
sql(q{UPDATE t SET extra='kept'; ALTER TABLE t DROP COLUMN x, ADD COLUMN newer int, ALTER COLUMN extra SET STATISTICS 80, ALTER COLUMN extra SET NOT NULL});
is(sql(q{SELECT * FROM t ORDER BY id}),"1|a|kept|\n2|b|kept|\n3|c|kept|",'mixed native drop and add preserves final attribute mapping');
is(sql(q{SELECT attname,attnum FROM pg_attribute WHERE attrelid='t'::regclass AND attnum>0 ORDER BY attnum}),"id|1\npayload|2\nextra|3\nnewer|4",'canonical publication compacts transient dropped-column slots');
rejects(q{ALTER TABLE t ADD COLUMN failed int, ALTER COLUMN failed SET COMPRESSION pglz},'failure in later pass rejects all layout changes');
is(sql(q{SELECT count(*) FROM pg_attribute WHERE attrelid='t'::regclass AND attname='failed'}),'0','failed multi-pass layout leaves no catalog residue');
rejects(q{ALTER TABLE t DROP COLUMN id},'indexed drop fails before physical storage deletion');
is(sql(q{SELECT count(*) FROM t WHERE id=2}),'1','failed indexed drop preserves data and indexes');
sql(q{BEGIN; ALTER TABLE t DROP COLUMN extra; ROLLBACK});
is(sql(q{SELECT extra FROM t ORDER BY id LIMIT 1}),'kept','layout and data publication roll back together');
$s->quit;$node->stop;done_testing();
