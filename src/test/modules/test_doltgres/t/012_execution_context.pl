use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('execution_context');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->append_conf('postgresql.conf',"default_table_access_method='dolt_prolly_table'\n");$node->start;
sub sql {return $node->safe_psql('postgres',$_[0]);}
sql(q{
CREATE TABLE t(id int PRIMARY KEY,v text) USING dolt_prolly_table;
CREATE TABLE _t(x int) USING dolt_prolly_table;
CREATE FUNCTION pg_catalog.pl_decl() RETURNS text LANGUAGE plpgsql STABLE AS $$DECLARE r public.t%ROWTYPE; BEGIN SELECT * INTO r FROM public.t; RETURN row_to_json(r)::text; END$$;
CREATE FUNCTION pg_catalog.pl_write() RETURNS void LANGUAGE plpgsql AS $$BEGIN UPDATE public.t SET v=v||'!'; END$$;
CREATE FUNCTION pg_catalog.pl_static(regclass) RETURNS text LANGUAGE plpgsql STABLE AS $$DECLARE answer text; BEGIN SELECT string_agg(v,',' ORDER BY id) INTO answer FROM public.t; RETURN answer; END$$;
CREATE FUNCTION pg_catalog.pl_dynamic(regclass) RETURNS text LANGUAGE plpgsql STABLE AS $$DECLARE answer text; BEGIN EXECUTE 'SELECT string_agg(v,'','' ORDER BY id) FROM public.t' INTO answer; RETURN answer; END$$;
CREATE FUNCTION pg_catalog.pl_rows(anyarray) RETURNS text LANGUAGE plpgsql STABLE AS $$DECLARE answer text; BEGIN SELECT string_agg(v,',' ORDER BY id) INTO answer FROM public.t; RETURN answer; END$$;
INSERT INTO t VALUES(1,'main'); SELECT dolt_commit('-Am','base');
SELECT dolt_checkout('-b','other'); ALTER TABLE t ADD COLUMN extra int; UPDATE t SET v='other',extra=7; SELECT dolt_commit('-Am','other'); SELECT dolt_checkout('main');
});
is(sql(q{SELECT pl_static(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'}),'other','PL static query inherits revision');
is(sql(q{SELECT pl_dynamic(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'}),'other','dynamic SQL inherits revision');
is(sql(q{SELECT pl_static(oid::regclass) FROM (SELECT oid FROM pg_class AS OF 'main' WHERE relname='t' UNION ALL SELECT oid FROM pg_class AS OF 'other' WHERE relname='t') q}),"main\nother",'PL compiled cache separates revisions at one call site');
is(sql(q{SELECT (ARRAY[ROW(1,'x')::t])[1].v}),'x','composite array constructor and subscript');
is(sql(q{SELECT (x).extra FROM (SELECT unnest(array_agg(t)) AS x FROM t AS OF 'other' t) q}),'7','historical aggregate arrays retain descriptor');
is(sql(q{SELECT pl_rows(array_agg(t)) FROM t AS OF 'other' t}),'other','polymorphic array selects revision');
is(sql(q{SELECT a.typname FROM pg_type t JOIN pg_type a ON a.oid=t.typarray WHERE t.typname='t'}),'_t_1','array names avoid canonical rowtype collision');
is(sql(q{SELECT (ROW(1,'x')::t)::text}),'(1,x)','composite text IO');
is(sql(q{SELECT (x).v FROM unnest('{"(1,x)"}'::t[]) x}),'x','array text input and unnest');
my $s=$node->background_psql('postgres',on_error_stop=>0);
$s->query_safe(q{PREPARE a(t[]) AS SELECT (x).v FROM unnest($1) x});
is($s->query_safe(q{EXECUTE a(ARRAY[ROW(1,'x')::t])}),'x','typed composite array parameter');
is($s->query_safe(q{SELECT pl_decl()::jsonb->>'v'}),'main','argument-free PL rowtype declaration on main');
$s->query_safe(q{SELECT dolt_checkout('other')});
is($s->query_safe(q{SELECT pl_decl()::jsonb->>'extra'}),'7','argument-free PL declaration rebinds after checkout');
my ($out,$failed)=$s->query(q{EXECUTE a(ARRAY[ROW(1,'other',7)::t])});
is($failed,1,'prepared parameter from incompatible revision rejected');
$s->{stderr}='';
$s->query_safe(q{SELECT dolt_checkout('main')});
is($s->query_safe(q{EXECUTE a(ARRAY[ROW(1,'y')::t])}),'y','prepared parameter recovers after checkout');
$s->query_safe(q{SELECT pl_write()});
is($s->query_safe(q{SELECT v FROM t}),'main!','compilation scope does not remove session write authority');
is($s->query_safe(q{SELECT v FROM t AS OF 'other'}),'other','procedural write stays on selected branch');
$s->quit;$node->stop;done_testing();
