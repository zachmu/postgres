use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('dependencies');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->append_conf('postgresql.conf',"default_table_access_method='dolt_prolly_table'\n");$node->start;
my $s=$node->background_psql('postgres',on_error_stop=>0);
sub sql {return $s->query_safe($_[0]);}
sub rejects {my ($out,$failed)=$s->query($_[0]);is($failed,1,$_[1]);like($s->{stderr},$_[2],$_[1].' diagnostic') if $_[2];$s->{stderr}='';}
sql(q{
SET client_min_messages=warning;
CREATE TABLE t(id int PRIMARY KEY,x int UNIQUE,y int) USING dolt_prolly_table;
CREATE INDEX extra_idx ON t USING dolt_prolly_index(y);
INSERT INTO t VALUES(1,2,3);
CREATE FUNCTION row_function(t) RETURNS int LANGUAGE sql AS $$SELECT ($1).id$$;
CREATE FUNCTION array_function(t[]) RETURNS int LANGUAGE sql AS $$SELECT cardinality($1)$$;
CREATE SCHEMA side;
CREATE TABLE side.u(id int PRIMARY KEY) USING dolt_prolly_table;
INSERT INTO side.u VALUES(7);
CREATE FUNCTION side.uf(side.u) RETURNS int LANGUAGE sql AS $$SELECT ($1).id$$;
SELECT dolt_commit('-Am','dependency base');
SELECT dolt_checkout('-b','other');
});
my $main=$node->background_psql('postgres',on_error_stop=>0);
$main->query_safe(q{SET statement_timeout='2s'; PREPARE stable_main AS SELECT count(*) FROM t});
rejects(q{DROP TABLE t},'RESTRICT follows routine signatures through row type and array',qr/cannot drop table t because other objects depend on it/);
is(sql(q{SELECT row_function(t),array_function(ARRAY[t]) FROM t}),'1|1','RESTRICT failure preserves table and dependent functions');
rejects(q{DROP TYPE t},'native internal ownership forbids dropping table row type directly');
rejects(q{ALTER TABLE t DROP CONSTRAINT t_id_not_null},'native validation preserves primary-key not-null requirement',qr/is in a primary key/);
rejects(q{DROP INDEX t_pkey},'native internal ownership protects constraint index');
sql(q{DROP INDEX extra_idx});
is(sql(q{SELECT count(*) FROM pg_class WHERE relname='extra_idx'}),'0','standalone index removed');
is(sql(q{SELECT count(*) FROM pg_index i JOIN pg_class c ON c.oid=i.indrelid WHERE c.relname='t'}),'2','parent descriptor retains remaining constraint indexes');
sql(q{INSERT INTO t VALUES(2,4,6)});
is(sql(q{SELECT sum(y) FROM t}),'9','metadata-only index removal preserves table storage and write path');
sql(q{BEGIN; ALTER TABLE t DROP CONSTRAINT t_x_key});
is(sql(q{SELECT count(*) FROM pg_index i JOIN pg_class c ON c.oid=i.indrelid WHERE c.relname='t'}),'1','constraint deletion follows ownership to its index');
sql(q{INSERT INTO t VALUES(3,2,9)});
is(sql(q{SELECT count(*) FROM t WHERE x=2}),'2','removed unique constraint no longer rejects duplicate data');
sql(q{ROLLBACK});
rejects(q{INSERT INTO t VALUES(3,2,9)},'constraint rollback restores uniqueness',qr/duplicate key/);
sql(q{BEGIN; DROP TABLE t CASCADE});
is($main->query_safe(q{EXECUTE stable_main}),'1','other branch prepared plan remains usable during open CASCADE');
$main->query_safe(q{UPDATE t SET y=10 WHERE id=1});
is($main->query_safe(q{SELECT y FROM t}),'10','other branch can write during open CASCADE');
is(sql(q{SELECT count(*) FROM pg_proc WHERE proname IN ('row_function','array_function')}),'0','CASCADE removes routines dependent on row type and array');
is(sql(q{SELECT count(*) FROM pg_class WHERE relname IN ('t','t_pkey','t_x_key')}),'0','CASCADE removes table and owned indexes');
sql(q{ROLLBACK});
is(sql(q{SELECT row_function(t) FROM t ORDER BY id}),"1\n2",'rollback restores whole dependency closure');
rejects(q{DROP SCHEMA side},'schema RESTRICT detects members');
sql(q{DROP SCHEMA side CASCADE});
is(sql(q{SELECT count(*) FROM pg_namespace WHERE nspname='side'}),'0','schema CASCADE removes canonical namespace');
is(sql(q{SELECT count(*) FROM pg_proc WHERE proname='uf'}),'0','schema CASCADE removes routine and table');
is(sql(q{SELECT id FROM side.u AS OF 'main'}),'7','retained schema and table remain readable');
sql(q{CREATE FUNCTION doubled(x int) RETURNS int LANGUAGE plpgsql IMMUTABLE AS $$BEGIN RETURN x*2; END$$; CREATE FUNCTION small(x int) RETURNS boolean LANGUAGE sql IMMUTABLE AS $$SELECT x < 100$$});
sql(q{CREATE TABLE calls(id int PRIMARY KEY, v int DEFAULT doubled(3), w int CHECK (small(w)), g int GENERATED ALWAYS AS (doubled(id)) STORED); INSERT INTO calls(id,w) VALUES (1,4)});
is(sql(q{SELECT v||','||w||','||g FROM calls}),'6,4,2','defaults, checks and generated columns call versioned routines');
rejects(q{INSERT INTO calls(id,w) VALUES (2,600)},'CHECK calling a versioned routine is enforced',qr/calls_w_check/);
rejects(q{DROP FUNCTION small(int)},'RESTRICT protects a routine a CHECK calls',qr/constraint calls_w_check on table calls depends on function small/);
rejects(q{DROP FUNCTION doubled(int)},'RESTRICT protects a routine a default calls',qr/default value for column v of table calls depends on function doubled/);
sql(q{DROP FUNCTION small(int) CASCADE; DROP FUNCTION doubled(int) CASCADE; INSERT INTO calls(id,w) VALUES (3,600)});
is(sql(q{SELECT count(*)||','||(SELECT v IS NULL FROM calls WHERE id=3) FROM pg_attrdef WHERE adrelid='calls'::regclass}),'0,true','CASCADE removes the dependent default and CHECK');
is(sql(q{SELECT string_agg(attname, ',' ORDER BY attnum) FROM pg_attribute WHERE attrelid='calls'::regclass AND attnum>0}),'id,v,w','and the generated column calling it, as native');
sql(q{CREATE TYPE level AS ENUM ('low','high'); CREATE TABLE cols(id int PRIMARY KEY, lv level, n int, keep text); INSERT INTO cols VALUES (1,'high',2,'kept');
CREATE INDEX cols_lv ON cols(lv, keep); CREATE INDEX cols_keep ON cols(keep); CREATE VIEW cols_v AS SELECT id, lv FROM cols; CREATE VIEW cols_w AS SELECT id, keep FROM cols});
sql(q{DROP TYPE level CASCADE});
is(sql(q{SELECT string_agg(attname, ',' ORDER BY attnum) FROM pg_attribute WHERE attrelid='cols'::regclass AND attnum>0}),'id,n,keep','DROP TYPE CASCADE drops the columns of its type');
is(sql(q{SELECT string_agg(relname, ',' ORDER BY relname) FROM pg_class WHERE relname LIKE 'cols%'}),'cols,cols_keep,cols_pkey,cols_w','and the indexes and views that use them');
is(sql(q{SET enable_seqscan=off; SELECT id||','||n||','||keep FROM cols WHERE keep='kept'; RESET enable_seqscan}),'1,2,kept','the table\'s rows and remaining indexes follow');
sql(q{CREATE TABLE refd(a int PRIMARY KEY, b int UNIQUE); CREATE TABLE refs(x int REFERENCES refd(b)); INSERT INTO refd VALUES (1,10); INSERT INTO refs VALUES (10)});
rejects(q{ALTER TABLE refd DROP COLUMN b},'a referenced column cannot be dropped alone',qr/constraint refs_x_fkey on table (public\.)?refs depends on index (public\.)?refd_b_key/);
sql(q{ALTER TABLE refd DROP COLUMN b CASCADE; INSERT INTO refs VALUES (99)});
is(sql(q{SELECT count(*) FROM pg_constraint WHERE conrelid='refs'::regclass}),'0','DROP COLUMN CASCADE drops another table\'s foreign key');
sql(q{DROP TABLE t CASCADE});
is(sql(q{SELECT count(*) FROM pg_type WHERE typname IN ('t','_t')}),'0','CASCADE removes generated row and array types');
is(sql(q{SELECT id FROM t AS OF 'main'}),'1','another branch retains its table rows');
is(sql(q{SELECT count(*) FROM pg_proc AS OF 'main' WHERE proname IN ('row_function','array_function')}),'2','another branch retains routine signatures');
sql(q{SELECT dolt_commit('-Am','drop closure')});
is($main->query_safe(q{EXECUTE stable_main}),'1','other branch prepared plan survives committed CASCADE');
$main->quit;
$s->quit;$node->stop;$node->start;
$s=$node->background_psql('postgres',on_error_stop=>0);
sql(q{SELECT dolt_checkout('other')});
is(sql(q{SELECT count(*) FROM pg_class WHERE relname='t'}),'0','dependency publication survives restart');
is(sql(q{SELECT id FROM t AS OF 'main'}),'1','retained root survives restart');
$s->quit;$node->stop;done_testing();
