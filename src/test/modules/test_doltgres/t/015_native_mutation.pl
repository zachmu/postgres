use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('native_mutation');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->start;
my $s=$node->background_psql('postgres',on_error_stop=>0);
sub sql {return $s->query_safe($_[0]);}
sub rejects {my ($out,$failed)=$s->query($_[0]);is($failed,1,$_[1]);$s->{stderr}='';}
sub attrs { return sql(q{SELECT attstattarget,attoptions FROM pg_attribute WHERE attrelid='t'::regclass AND attname='x'}); }
sql(q{SET client_min_messages=warning;
CREATE TABLE t(id int,x int) USING heap;
INSERT INTO t VALUES(1,10);
ALTER TABLE t ALTER COLUMN x SET STATISTICS 55;
ALTER TABLE t ALTER COLUMN x SET (n_distinct=10);
ALTER TABLE t SET ACCESS METHOD dolt_prolly_table;
SELECT dolt_commit('-Am','native attribute values');
SELECT dolt_checkout('-b','other');});
is(attrs(),'55|{n_distinct=10}','capture preserves native nullable catalog fields');
my $root_query=q{SELECT encode(reftarget,'hex') FROM pg_dolt_ref WHERE refname='working/other'};
my $original=sql($root_query);
sql(q{ALTER TABLE t ALTER COLUMN x SET STATISTICS 56; ALTER TABLE t ALTER COLUMN x SET STATISTICS 55});
is(sql($root_query),$original,'native tuple roundtrip restores canonical database hash');
rejects(q{ALTER TABLE t ALTER COLUMN x SET STATISTICS 200, ALTER COLUMN x SET (invalid_option=1)},'later native validator rolls back earlier action');
is(attrs(),'55|{n_distinct=10}','multi-action statement failure is atomic');
sql(q{ALTER TABLE t ALTER COLUMN x SET STATISTICS 199, ALTER COLUMN x SET STATISTICS 200});
is(attrs(),'200|{n_distinct=10}','native statistics tuple proposal published');
sql(q{ALTER TABLE t ALTER COLUMN x SET (n_distinct=-0.5,n_distinct_inherited=20)});
is(attrs(),'200|{n_distinct=-0.5,n_distinct_inherited=20}','native options tuple proposal published');
rejects(q{ALTER TABLE t ALTER COLUMN x SET (n_distinct= -2)},'native option validator rejects invalid value');
rejects(q{ALTER TABLE t ALTER COLUMN x SET STATISTICS -2},'native statistics validator rejects negative value');
rejects(q{ALTER TABLE t ALTER COLUMN missing SET STATISTICS 5},'native missing-column diagnostic');
rejects(q{ALTER TABLE t ALTER COLUMN ctid SET STATISTICS 5},'native system-column guard');
is(attrs(),'200|{n_distinct=-0.5,n_distinct_inherited=20}','failed native proposals leave canonical definition unchanged');
sql(q{BEGIN; ALTER TABLE t ALTER COLUMN x SET STATISTICS DEFAULT; ALTER TABLE t ALTER COLUMN x RESET (n_distinct,n_distinct_inherited)});
is(attrs(),'|','defaults use absent nullable fields');
sql('ROLLBACK');
is(attrs(),'200|{n_distinct=-0.5,n_distinct_inherited=20}','rollback restores all proposed metadata');
my $main=$node->background_psql('postgres',on_error_stop=>0);
$main->query_safe(q{SET statement_timeout='2s'; BEGIN; ALTER TABLE t ALTER COLUMN x SET STATISTICS 99});
sql(q{BEGIN; ALTER TABLE t ALTER COLUMN x SET STATISTICS 201; UPDATE t SET x=11; COMMIT});
is(attrs(),'201|{n_distinct=-0.5,n_distinct_inherited=20}','other-branch open metadata write does not block');
$main->query_safe('COMMIT');
is($main->query_safe(q{SELECT attstattarget FROM pg_attribute WHERE attrelid='t'::regclass AND attname='x'}),'99','parallel branch metadata remains isolated');
is(sql(q{SELECT attstattarget FROM pg_attribute AS OF 'HEAD' WHERE attname='x'}),'55','historical catalog retains native attribute values');
is(sql('SELECT x FROM t'),'11','metadata mutation preserves usable row storage');
sql(q{SELECT dolt_commit('-Am','metadata update')});
$s->quit;$main->quit;
$node->restart;
$s=$node->background_psql('postgres',on_error_stop=>0);
sql(q{SELECT dolt_checkout('other')});
is(attrs(),'201|{n_distinct=-0.5,n_distinct_inherited=20}','metadata survives restart');
$s->quit;
$node->stop;done_testing();
