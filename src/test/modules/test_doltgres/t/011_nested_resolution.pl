use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('nested_resolution');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->start;
sub sql {return $node->safe_psql('postgres',$_[0]);}
# Shared bootstrap helpers test SQL execution; user routines are not versioned yet.
sql(q{
CREATE TABLE t(id int PRIMARY KEY,v text) USING dolt_prolly_table;
CREATE TABLE only_main(v text) USING dolt_prolly_table;
CREATE SCHEMA a; CREATE SCHEMA b;
CREATE TABLE a.x(id int) USING dolt_prolly_table;
CREATE INDEX mask ON a.x USING dolt_prolly_index(id);
CREATE TABLE b.mask(v text) USING dolt_prolly_table;
CREATE TABLE a.int4(v text) USING dolt_prolly_table;
CREATE FUNCTION pg_catalog.dg_cast(regclass) RETURNS bool LANGUAGE SQL STABLE AS $$ SELECT pg_typeof(NULL::t)::oid = (SELECT reltype FROM pg_class WHERE oid=$1) $$;

CREATE FUNCTION pg_catalog.dg_nested(regclass) RETURNS text LANGUAGE SQL STABLE AS
$$ SELECT string_agg(attname,',' ORDER BY attnum) FROM pg_attribute WHERE attrelid=$1 AND attnum>0 AND NOT attisdropped $$;
CREATE FUNCTION pg_catalog.dg_type(regtype) RETURNS text LANGUAGE SQL STABLE AS $$ SELECT dg_nested(typrelid::regclass) FROM pg_type WHERE oid=$1 $$;
CREATE FUNCTION pg_catalog.dg_fail(regclass) RETURNS int LANGUAGE SQL STABLE AS $$ SELECT 1 / (count(*)::int-count(*)::int) FROM pg_attribute WHERE attrelid=$1 $$;
CREATE FUNCTION pg_catalog.dg_leaf() RETURNS text LANGUAGE SQL STABLE AS $$ SELECT string_agg(v,',' ORDER BY id) FROM public.t $$;
CREATE FUNCTION pg_catalog.dg_leafcaller(regclass) RETURNS text LANGUAGE SQL STABLE AS $$ SELECT dg_leaf() $$;
CREATE FUNCTION pg_catalog.dg_outer(regclass) RETURNS text LANGUAGE SQL STABLE AS $$ SELECT dg_nested($1) $$;
CREATE FUNCTION pg_catalog.dg_body(regclass) RETURNS text LANGUAGE SQL STABLE AS $$ SELECT string_agg(v,',' ORDER BY id) FROM t $$;
CREATE FUNCTION pg_catalog.dg_poly(anyelement) RETURNS text LANGUAGE SQL STABLE AS $$ SELECT dg_body('t'::regclass) $$;
CREATE FUNCTION pg_catalog.dg_visible(regclass) RETURNS bool LANGUAGE SQL STABLE AS $$ SELECT pg_table_is_visible('pg_catalog.pg_class'::regclass) $$;
CREATE FUNCTION pg_catalog.dg_pair(regclass,regclass) RETURNS int LANGUAGE SQL STABLE AS $$ SELECT 1 $$;
CREATE FUNCTION pg_catalog.dg_set(regclass) RETURNS SETOF text LANGUAGE SQL STABLE AS $$ SELECT attname::text FROM pg_attribute WHERE attrelid=$1 AND attnum>0 AND NOT attisdropped ORDER BY attnum $$;
INSERT INTO t VALUES(1,'main');
SELECT dolt_commit('-Am','base');
SELECT dolt_checkout('-b','other');
DROP TABLE only_main;
CREATE TABLE a.pg_class(x int);
ALTER TABLE t ADD COLUMN extra int;
UPDATE t SET v='other',extra=7;
SELECT dolt_commit('-Am','other');
SELECT dolt_checkout('main');
});
is(sql(q{SELECT (ROW(1,'x')::public.t).v}),'x','qualified canonical composite type');
is(sql(q{SELECT (ROW(1,'y')::t).v}),'y','unqualified canonical composite type');
is(sql(q{SELECT pg_type_is_visible(reltype) FROM pg_class WHERE relname='t'}),'t','canonical rowtype visibility');
is(sql(q{SELECT dg_outer(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'}),'id,v,extra','nested regclass context');
is(sql(q{SELECT dg_body(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'}),'other','nested table lookup uses argument revision');
is(sql(q{SELECT dg_poly(t) FROM t AS OF 'other' t}),'other','polymorphic composite selects revision');
is(sql(q{SELECT dg_body(a.oid::regclass),dg_body(b.oid::regclass) FROM pg_class AS OF 'main' a CROSS JOIN pg_class AS OF 'other' b WHERE a.relname='t' AND b.relname='t'}),'main|other','separate calls use separate function cache contexts');
is(sql(q{SELECT dg_set(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'}),"id\nv\nextra",'set-returning function retains revision');
is(sql(q{SELECT x FROM pg_class AS OF 'other' c CROSS JOIN LATERAL dg_set(c.oid::regclass) x WHERE c.relname='t'}),"id\nv\nextra",'FROM function retains revision');
my ($status,$out,$err)=$node->psql('postgres',q{SELECT dg_pair(a.oid::regclass,b.oid::regclass) FROM pg_class AS OF 'main' a CROSS JOIN pg_class AS OF 'other' b WHERE a.relname='t' AND b.relname='t'});
like($err,qr/incompatible catalog contexts/,'ambiguous function context fails closed');
is(sql(q{SELECT dg_body('t'::regclass)}),'main','caller context unaffected');
is(sql(q{SELECT dg_type(reltype::regtype) FROM pg_class AS OF 'other' WHERE relname='t'}),'id,v,extra','regtype selects nested catalog context');
is(sql(q{SELECT dg_cast(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'}),'t','named type inside nested function matches revision');
is(sql(q{SET search_path=a,b; SELECT (ROW('x')::mask).v}),'x','index name does not shadow a type');
is(sql(q{SET search_path=a,pg_catalog; SELECT (ROW('x')::int4).v}),'x','explicit path can shadow a native type');
is(sql(q{SET search_path=a; SELECT 42::int4}),'42','implicit catalog precedes user type');
is(sql(q{SET search_path=a,pg_catalog; SELECT pg_type_is_visible('pg_catalog.int4'::regtype)}),'f','native type visibility honors canonical shadow');
is(sql(q{SELECT dg_leafcaller(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'}),'other','argument-free nested call inherits context');
is(sql(q{SELECT dg_outer(oid::regclass) FROM (SELECT oid FROM pg_class AS OF 'main' WHERE relname='t' UNION ALL SELECT oid FROM pg_class AS OF 'other' WHERE relname='t') s}),"id,v\nid,v,extra",'one call site switches compiled function context');
is(sql(q{SELECT ROW(1,'x')::t = ROW(1,'x')::t}),'t','native record comparison uses canonical descriptor');
is(sql(q{SELECT to_jsonb(t)->>'extra' FROM t AS OF 'other' t}),'7','native polymorphic JSON conversion uses historical rowtype');
is(sql(q{SELECT dg_poly(CASE WHEN false THEN t ELSE NULL END) FROM t AS OF 'other' t}),'other','null composite argument retains its type context');
is(sql(q{SELECT oprname FROM pg_operator AS OF 'other' WHERE oprname='=' AND oprleft='record'::regtype AND oprright='record'::regtype}),'=','bootstrap operator metadata available in a revision');
is(sql(q{SET search_path=a,pg_catalog; SELECT dg_visible(oid::regclass) FROM pg_catalog.pg_class AS OF 'other' WHERE relname='t'}),'f','native relation visibility honors enclosing revision');
my $s=$node->background_psql('postgres', on_error_stop=>0);
$s->query_safe(q{SELECT dolt_checkout('other')});
my ($missing,$missing_failed)=$s->query(q{SELECT NULL::only_main});
is($missing_failed,1,'absent branch rowtype cannot fall back to physical catalog');
like($s->{stderr},qr/type "only_main" does not exist/,'missing canonical type diagnostic');
$s->{stderr}='';
is($s->query_safe(q{SELECT (ROW(1,'z',9)::t).extra}),'9','named type follows selected branch');
$s->query_safe(q{PREPARE p AS SELECT dg_outer(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'});
is($s->query_safe('EXECUTE p'),'id,v,extra','prepared nested revision');
$s->query_safe(q{SELECT dolt_checkout('main')});
is($s->query_safe('EXECUTE p'),'id,v,extra','prepared nested revision survives checkout');
$s->query_safe(q{PREPARE r AS SELECT (ROW(1,'x')::t).v});
is($s->query_safe('EXECUTE r'),'x','prepared canonical type');
is($s->query_safe(q{BEGIN; SAVEPOINT s; SELECT dg_pair(a.oid::regclass,b.oid::regclass) FROM pg_class AS OF 'main' a CROSS JOIN pg_class AS OF 'main' b WHERE a.relname='t' AND b.relname='t'; ROLLBACK TO s; SELECT dg_body('t'::regclass); COMMIT}),"1\nmain",'same-context arguments and transaction restore');
$s->query_safe('BEGIN; SAVEPOINT before_error');
my ($ignored,$failed)=$s->query(q{SELECT dg_fail(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'});
is($failed,1,'nested SQL body raises an error');
like($s->{stderr},qr/division by zero/,'expected nested body error');
$s->{stderr}='';
$s->query_safe('ROLLBACK TO before_error');
is($s->query_safe(q{SELECT dg_outer('t'::regclass)}),'id,v','error restores caller context in the same backend');
$s->query_safe('COMMIT');
$s->query_safe(q{SELECT dolt_checkout('other')});
my ($unused,$type_failed)=$s->query('EXECUTE r');
is($type_failed,1,'prepared named type reanalyzes after checkout instead of retaining old shape');
like($s->{stderr},qr/too few columns/,'prepared type reports incompatible row shape');
$s->{stderr}='';
$s->query_safe(q{SELECT dolt_checkout('main')});
is($s->query_safe('EXECUTE r'),'x','prepared named type recovers on original branch');
sql(q{SELECT dolt_checkout('other'); ALTER TABLE t ADD COLUMN later int; SELECT dolt_commit('-Am','later')});
is($s->query_safe('EXECUTE p'),'id,v,extra,later','prepared nested body rebinds after revision advances');
is($s->query_safe(q{SELECT dg_outer('t'::regclass)}),'id,v','other session DDL leaves current branch type intact');
$s->quit;
$node->stop; $node->start;
is(sql(q{SELECT dg_outer(oid::regclass) FROM pg_class AS OF 'other' WHERE relname='t'}),'id,v,extra,later','cold nested catalog binding');

$node->stop;done_testing();
