# End-to-end SQL DDL/DML: no physical schema rows, per-branch visibility.
use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('canonical_sql');
$node->init(allows_streaming=>1,extra=>['--encoding=UTF8','--locale=C']);$node->start;
sub sql { return $node->safe_psql('postgres',$_[0]); }
sub fails { my($q,$pattern,$label)=@_;my($s,$o,$e)=$node->psql('postgres',$q);isnt($s,0,$label);like($e,$pattern,"$label diagnostic"); }
sql(q{CREATE FUNCTION pg_catalog.test_physical_class(text) RETURNS int AS 'storage_resource','test_physical_class' LANGUAGE C STRICT;
CREATE TABLE seed(id int) USING dolt_prolly_table; SELECT dolt_commit('-Am','base'); SELECT dolt_checkout('-b','other')});
my $main=$node->background_psql('postgres');
my $other=$node->background_psql('postgres');
$other->query_safe(q{SELECT dolt_checkout('other')});
$main->query_safe(q{CREATE TABLE t(id int PRIMARY KEY,v int UNIQUE); INSERT INTO t VALUES(1,10); PREPARE main_read AS SELECT * FROM t ORDER BY id; PREPARE main_write(int,int) AS INSERT INTO t VALUES($1,$2)});
is($main->query_safe('EXECUTE main_read'),'1|10','ordinary SQL uses canonical main definition');
is(sql(q{SELECT test_physical_class('t'),test_physical_class('t_pkey'),test_physical_class('t_v_key')}),'0|0|0','table and indexes have no physical pg_class schema rows');
is($main->query_safe(q{SELECT 't'::regclass::oid=c.oid FROM pg_class c WHERE relname='t'}),'t','regclass and ordinary catalog scan agree on branch identity');
$other->query_safe(q{BEGIN; CREATE TABLE t(id int PRIMARY KEY,v text UNIQUE,note text); INSERT INTO t VALUES(1,'ten','pending')});
is($other->query_safe('SELECT * FROM t'),'1|ten|pending','own transaction sees provisional schema and data');
is(sql(q{SELECT to_regclass('t') IS NOT NULL}),'t','main definition remains visible during other DDL');
$main->query_safe(q{SET statement_timeout='2s'; EXECUTE main_write(2,20)});
is($main->query_safe('EXECUTE main_read'),"1|10\n2|20",'other branch open DDL does not block prepared writes or change definition');
is($main->query_safe(q{BEGIN; DECLARE c CURSOR FOR SELECT * FROM t ORDER BY id; FETCH 1 FROM c}),'1|10','main cursor pins its own schema');
is(sql(q{SELECT count(*) FROM "postgres/other".pg_catalog.pg_class WHERE relname='t'}),'0','concurrent session cannot see uncommitted branch schema');
$other->query_safe('COMMIT');
is($main->query_safe('FETCH ALL FROM c'),'2|20','cursor survives other branch schema publication');
$main->query_safe('COMMIT');
is($main->query_safe('EXECUTE main_read'),"1|10\n2|20",'prepared statement survives incompatible other schema commit');
is(sql(q{SELECT row_to_json(a),row_to_json(b) FROM "postgres/main".public.t a JOIN "postgres/other".public.t b USING(id)}),'{"id":1,"v":10}|{"id":1,"v":"ten","note":"pending"}','one query reads incompatible row types');
is($other->query_safe(q{SELECT string_agg(attname||':'||format_type(atttypid,atttypmod),',' ORDER BY attnum) FROM pg_attribute WHERE attrelid='t'::regclass AND attnum>0}),'id:integer,v:text,note:text','ordinary pg_attribute uses session branch');
is(sql("COPY t FROM STDIN;\n9\t90\n\\.\n"),'','COPY FROM accepts a canonical resource');
is(join("\n",sort split(/\n/,$main->query_safe('COPY t TO STDOUT'))), "1\t10\n2\t20\n9\t90", 'COPY TO reads the bound canonical resource');
$main->query_safe('DELETE FROM t WHERE id=9');
$other->query_safe(q{BEGIN; DROP TABLE t; CREATE TABLE t(id int,v bool); INSERT INTO t VALUES(3,true)});
is($main->query_safe('EXECUTE main_read'),"1|10\n2|20",'uncommitted DROP/recreate is isolated');
$other->query_safe('ROLLBACK');
is($other->query_safe('SELECT * FROM t'),'1|ten|pending','rollback restores original schema and data');
$other->query_safe(q{BEGIN; SAVEPOINT s; DROP TABLE t; CREATE TABLE t(x text); ROLLBACK TO s; INSERT INTO t VALUES(2,'two','after rollback'); COMMIT});
is($other->query_safe('SELECT count(*) FROM t'),'2','savepoint rollback restores usable canonical binding');
$main->query_safe(q{BEGIN; EXECUTE main_write(3,30)});
is($main->query_safe(q{SELECT count(*) FROM pg_locks WHERE pid=pg_backend_pid() AND locktype='relation' AND relation>=3221225472::oid}),'0','prepared SQL writes use no shared locks on local handles');
$main->query_safe('ROLLBACK');
$main->query_safe(q{SELECT dolt_commit('-Am','main schema')});
$other->query_safe(q{SELECT dolt_commit('-Am','other schema')});
$main->quit;$other->quit;
$node->stop('immediate');$node->start;
is(sql(q{SELECT a.v,b.v FROM "postgres/main".public.t a JOIN "postgres/other".public.t b USING(id) ORDER BY id}),"10|ten\n20|two",'restart recovers both canonical schemas and roots');
is(sql(q{SELECT test_physical_class('t')}),'0','restart needs no physical schema materialization');
$node->backup('canonical');
my $standby=PostgreSQL::Test::Cluster->new('canonical_standby');$standby->init_from_backup($node,'canonical',has_streaming=>1);$standby->start;
is($standby->safe_psql('postgres',q{SELECT a.v,b.v FROM "postgres/main".public.t a JOIN "postgres/other".public.t b USING(id) ORDER BY id}),"10|ten\n20|two",'standby resolves canonical definitions automatically');
$standby->stop;
my $pending=$node->background_psql('postgres');$pending->query_safe(q{BEGIN; CREATE TABLE crash_table(id int PRIMARY KEY); INSERT INTO crash_table VALUES(1)});
$node->stop('immediate');$pending->quit;$node->start;
is(sql(q{SELECT to_regclass('crash_table') IS NULL}),'t','crash discards uncommitted schema and data publication');
is(sql(q{SELECT count(*) FROM dolt_diff_summary('HEAD','WORKING')}),'0','crash leaves no partial working membership');
fails(q{CREATE TABLE bad_index(id int CONSTRAINT bad_index PRIMARY KEY)},qr/already exists/,'index and table cannot share one canonical name');
is(sql(q{SELECT count(*) FROM pg_tables WHERE schemaname='public' AND tablename='t'}),'1','stored catalog view exposes the canonical table without physical schema rows');
$node->stop;done_testing();
