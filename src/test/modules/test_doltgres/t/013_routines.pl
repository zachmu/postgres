use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('routines');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->start;
$node->safe_psql('postgres','CREATE DATABASE empty_routines');
my $s=$node->background_psql('postgres',on_error_stop=>0);
sub sql {return $s->query_safe($_[0]);}
sql(q{
CREATE TABLE t(id int PRIMARY KEY,v text) USING dolt_prolly_table;
INSERT INTO t VALUES(1,'main');
CREATE FUNCTION public.f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input||'_main'; END$$;
CREATE FUNCTION public.rows() RETURNS text LANGUAGE sql STABLE AS $$SELECT v FROM public.t$$;
SELECT dolt_commit('-Am','base');
SELECT dolt_checkout('-b','other');
});
is(sql(q{SELECT f('x')}),'x_main','initial routine captured and callable');
sql(q{CREATE OR REPLACE FUNCTION public.f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input||'_other'; END$$});
is(sql(q{SELECT f('x')}),'x_other','replacement visible on selected branch');
sql(q{UPDATE t SET v='other'; SELECT dolt_commit('-Am','other'); SELECT dolt_checkout('main')});
is(sql(q{SELECT f('x')}),'x_main','checkout restores function body');
is(sql(q{SELECT rows()}),'main','SQL body uses routine revision');
is(sql(q{SELECT count(*) FROM pg_proc AS OF 'other' WHERE proname='f'}),'1','historical catalog exposes canonical routine');
$s->query_safe(q{PREPARE fcall AS SELECT f('x')});
is($s->query_safe(q{EXECUTE fcall}),'x_main','prepared routine initial branch');
$s->query_safe(q{SELECT dolt_checkout('other')});
is($s->query_safe(q{EXECUTE fcall}),'x_other','prepared routine rebinds after checkout');
$s->query_safe(q{BEGIN; CREATE OR REPLACE FUNCTION f(input text) RETURNS text LANGUAGE sql AS $$SELECT input||'_abort'$$; ROLLBACK});
is($s->query_safe(q{SELECT f('x')}),'x_other','rollback restores definition');
$s->query_safe(q{SET search_path=public,pg_catalog,public; SELECT dolt_checkout('main')});
is($s->query_safe(q{SELECT f('x')}),'x_main','uncached search path resolves canonical main namespace');
$s->query_safe(q{SELECT dolt_checkout('other')});
is($s->query_safe(q{SELECT f('x')}),'x_other','search path cache does not retain old revision handles');
$s->query_safe(q{CREATE FUNCTION write_row() RETURNS text LANGUAGE plpgsql AS $$DECLARE answer text; BEGIN UPDATE t SET v=v||'!'; SELECT v INTO answer FROM t; RETURN answer; END$$});
is($s->query_safe(q{SELECT write_row()}),'other!','working routine writes and reads its own changes');
is($s->query_safe(q{SELECT v FROM t AS OF 'main'}),'main','routine write leaves another branch unchanged');
$s->quit;
my $e=$node->background_psql('empty_routines',on_error_stop=>0);
$e->query_safe(q{CREATE FUNCTION f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input; END$$; SELECT dolt_add('.')});
my ($out,$failed)=$e->query(q{SELECT length(dolt_commit('-m','invalid nested commit'))});
is($failed,1,'nested version-control commit rejected');$e->{stderr}='';
$e->query_safe(q{SELECT dolt_checkout('-b','other')});
($out,$failed)=$e->query(q{CREATE OR REPLACE FUNCTION f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input||'!'; END$$});
is($failed,1,'genesis revision with no namespace rejects creation without physical fallback');$e->{stderr}='';
$e->query_safe(q{SELECT dolt_checkout('main')});
$e->query_safe(q{CREATE OR REPLACE FUNCTION f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input||'!'; END$$});
is($e->query_safe(q{SELECT f('x')}),'x!','routine creation recovers after missing canonical namespace');
$e->quit;$node->stop;done_testing();
