use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('foreign_keys');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->start;
my $s=$node->background_psql('postgres',on_error_stop=>0);
sub sql { $s->query_safe($_[0]); }
sub rejects {my($out,$failed)=$s->query($_[0]);is($failed,1,$_[1]);diag($s->{stderr}) unless $failed;$s->{stderr}='';}
sql(q{SET statement_timeout='10s'; SET client_min_messages=warning;
CREATE TABLE parent(id int PRIMARY KEY) USING dolt_prolly_table;
CREATE TABLE child(id int PRIMARY KEY,pid int) USING dolt_prolly_table;
INSERT INTO parent VALUES(1); INSERT INTO child VALUES(1,1);
SELECT dolt_commit('-Am','base'); SELECT dolt_checkout('-b','other')});
sql(q{ALTER TABLE child ADD CONSTRAINT child_fk FOREIGN KEY(pid) REFERENCES parent(id) NOT VALID});
is(sql(q{SELECT count(*) FROM pg_trigger WHERE tgconstraint=(SELECT oid FROM pg_constraint WHERE conname='child_fk')}),'4','canonical foreign key reconstructs native triggers');
is(sql(q{SELECT * FROM parent}),'1','parent remains readable after constraint publication');
sql(q{INSERT INTO child VALUES(2,1)});
rejects(q{INSERT INTO child VALUES(3,99)},'foreign key rejects missing parent');
rejects(q{DELETE FROM parent WHERE id=1},'NO ACTION protects referenced row');
sql(q{ALTER TABLE child VALIDATE CONSTRAINT child_fk});
is(sql(q{SELECT convalidated FROM pg_constraint WHERE conname='child_fk'}),'t','VALIDATE publishes constraint state');
sql(q{ALTER TABLE child DROP CONSTRAINT child_fk, ADD CONSTRAINT child_fk FOREIGN KEY(pid) REFERENCES parent(id) ON UPDATE CASCADE ON DELETE CASCADE});
sql(q{UPDATE parent SET id=10 WHERE id=1});
is(sql(q{SELECT pid FROM child ORDER BY id}),"10\n10",'UPDATE CASCADE uses branch-local child');
sql(q{DELETE FROM parent WHERE id=10});
is(sql(q{SELECT count(*) FROM child}),'0','DELETE CASCADE removes branch-local children');
sql(q{ALTER TABLE child DROP CONSTRAINT child_fk, ADD CONSTRAINT child_fk FOREIGN KEY(pid) REFERENCES parent(id) DEFERRABLE INITIALLY DEFERRED});
sql(q{BEGIN; INSERT INTO child VALUES(3,3); INSERT INTO parent VALUES(3); SET CONSTRAINTS child_fk IMMEDIATE; COMMIT});
is(sql(q{SELECT pid FROM child}),'3','deferred trigger survives statement executor lifetime');
rejects(q{BEGIN; INSERT INTO child VALUES(4,4); COMMIT},'deferred trigger rejects orphan at commit');
is(sql(q{SELECT count(*) FROM child}),'1','failed deferred commit rolls back child');
sql(q{CREATE TABLE inline_fk(id int PRIMARY KEY,pid int REFERENCES parent(id) ON DELETE SET NULL); INSERT INTO inline_fk VALUES(1,3)});
rejects(q{INSERT INTO inline_fk VALUES(2,99)},'inline CREATE foreign key enforces referenced rows');
sql(q{DELETE FROM child; DELETE FROM parent WHERE id=3});
is(sql(q{SELECT pid IS NULL FROM inline_fk}),'t','SET NULL updates referencing column');
sql(q{SELECT dolt_commit('-Am','foreign keys')});
is(sql(q{SELECT count(*) FROM pg_constraint AS OF 'main' WHERE contype='f'}),'0','foreign keys are isolated from main schema');
sql(q{BEGIN; ALTER TABLE child DROP CONSTRAINT child_fk; ROLLBACK});
is(sql(q{SELECT count(*) FROM pg_constraint WHERE conname='child_fk'}),'1','constraint deletion rolls back');
rejects(q{DROP TABLE parent},'dependency closure protects referenced table');
sql(q{BEGIN; DROP TABLE parent CASCADE});
is(sql(q{SELECT count(*) FROM pg_constraint WHERE contype='f'}),'0','CASCADE removes referencing constraints and generated triggers');
sql(q{ROLLBACK});
sql(q{INSERT INTO parent VALUES(9); INSERT INTO child VALUES(9,9); SELECT dolt_commit('-Am','retained rows')});
my $peer=$node->background_psql('postgres',on_error_stop=>0);
$peer->query_safe(q{SET statement_timeout='3s'; SET client_min_messages=warning; SELECT dolt_checkout('main'); BEGIN; ALTER TABLE child ADD CONSTRAINT main_fk FOREIGN KEY(pid) REFERENCES parent(id)});
sql(q{BEGIN; ALTER TABLE child ALTER CONSTRAINT child_fk NOT DEFERRABLE; INSERT INTO child VALUES(10,9)});
$peer->query_safe(q{INSERT INTO child VALUES(2,1); COMMIT});sql(q{COMMIT});
is(sql(q{SELECT pid FROM child ORDER BY id}),"9\n9",'parallel branch DDL and RI writes remain independent');
$peer->quit;
$s->quit;$node->stop('immediate');$node->start;
$s=$node->background_psql('postgres',on_error_stop=>0);
sql(q{SET client_min_messages=warning; SELECT dolt_checkout('other')});
rejects(q{INSERT INTO child VALUES(11,99)},'recovered triggers retain branch enforcement');
is(sql(q{SELECT pid FROM child ORDER BY id}),"9\n9",'crash recovery preserves branch data');
$s->quit;$node->stop;done_testing();
