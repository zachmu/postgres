use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('index_lifecycle');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->append_conf('postgresql.conf',"default_table_access_method='dolt_prolly_table'\n");$node->start;
my $s=$node->background_psql('postgres',on_error_stop=>0);
sub sql { $s->query_safe($_[0]); }
sub rejects {my($out,$failed)=$s->query($_[0]);is($failed,1,$_[1]);diag($s->{stderr}) unless $failed;$s->{stderr}='';}
sql(q{SET statement_timeout='10s'; SET client_min_messages=warning;
CREATE TABLE t(id int PRIMARY KEY,x int,v text) USING dolt_prolly_table;
INSERT INTO t VALUES(1,10,'a'),(2,20,'b');
SELECT dolt_commit('-Am','base'); SELECT dolt_checkout('-b','other')});
# TODO: index ownership, once the ownership and ACL design settles who owns
# a versioned table.
my $initial=sql(q{SELECT dolt_hashof_db()});
sql(q{CREATE INDEX temporary_idx ON t(v); DROP INDEX temporary_idx});
is(sql(q{SELECT dolt_hashof_db()}),$initial,'index create/drop preserves canonical history independence');
sql(q{CREATE UNIQUE INDEX x_idx ON t(x)});
is(sql(q{SELECT indexname FROM pg_indexes WHERE tablename='t' ORDER BY indexname}),"t_pkey\nx_idx",'independent index creation publishes canonical index');
rejects(q{INSERT INTO t VALUES(3,10,'duplicate')},'new unique index validates writes');
rejects(q{INSERT INTO t VALUES(3,10,'duplicate') ON CONFLICT DO NOTHING},'unsupported conflict snapshot releases private index scan pins safely');
is(sql(q{SELECT count(*) FROM t}),'2','index scan failure leaves session usable');
sql(q{SET enable_seqscan=off});
is(sql(q{SELECT indkey::text FROM pg_index WHERE indexrelid='x_idx'::regclass}),'2','new index binds the correct table attribute');
my $before=sql(q{SELECT dolt_hashof_db()});
sql(q{CREATE UNIQUE INDEX IF NOT EXISTS x_idx ON t(x)});
is(sql(q{SELECT dolt_hashof_db()}),$before,'IF NOT EXISTS keeps canonical state');
rejects(q{ALTER TABLE t ALTER COLUMN x TYPE bigint USING 1::bigint},'duplicate keys abort index replacement');
is(sql(q{SELECT dolt_hashof_db()}),$before,'failed rewrite leaves complete original state');
sql(q{ALTER TABLE t ALTER COLUMN x TYPE bigint USING x::bigint+1});
is(sql(q{SET enable_seqscan=off; SELECT x,pg_typeof(x) FROM t WHERE x=11}),'11|bigint','indexed TYPE rebuild uses rewritten rows');
sql(q{ALTER TABLE t DROP COLUMN id});
is(sql(q{SELECT * FROM t ORDER BY x}),"11|a\n21|b",'indexed DROP compacts rows');
is(sql(q{SELECT indexname FROM pg_indexes WHERE tablename='t' ORDER BY indexname}),'x_idx','owned primary index deleted with column');
sql(q{ALTER TABLE t ADD CONSTRAINT v_unique UNIQUE(v)});
rejects(q{INSERT INTO t VALUES(30,'a')},'native unique constraint creates a published index');
sql(q{CREATE TABLE "odd table"(id int, "odd col" text); CREATE INDEX "odd ""key" ON "odd table"("odd col"); ALTER TABLE "odd table" DROP COLUMN "odd col"});
is(sql(q{SELECT count(*) FROM pg_indexes WHERE tablename='odd table'}),'0','quoted index identity is removed with indexed column');
sql(q{DROP TABLE "odd table"});
sql(q{SELECT dolt_commit('-Am','indexed schema')});
my $schema=sql(q{SELECT dolt_hashof_db()});
sql(q{BEGIN; SAVEPOINT keep; ALTER TABLE t DROP COLUMN x; ROLLBACK TO keep; COMMIT});
is(sql(q{SELECT dolt_hashof_db()}),$schema,'savepoint restores dropped index schema and rows');
sql(q{BEGIN; ALTER TABLE t ALTER COLUMN x TYPE integer USING x::integer; ROLLBACK});
is(sql(q{SELECT x,pg_typeof(x) FROM t ORDER BY x}),"11|bigint\n21|bigint",'transaction rollback restores original index key types');
sql(q{ALTER TABLE t ADD CONSTRAINT new_pk PRIMARY KEY(x)});
rejects(q{ALTER TABLE t DROP CONSTRAINT new_pk, ADD CONSTRAINT impossible CHECK(x<0)},'late constraint failure rolls index deletion back');
rejects(q{INSERT INTO t VALUES(NULL,'null')},'native primary key adds NOT NULL');
sql(q{ALTER TABLE t DROP CONSTRAINT new_pk});
rejects(q{DROP INDEX v_unique},'native dependency protects constraint-owned index');
sql(q{DROP INDEX x_idx; CREATE INDEX x_idx ON t(x DESC) INCLUDE(v)});
is(sql(q{SELECT x,v FROM t WHERE x>=11 ORDER BY x DESC}),"21|b\n11|a",'replacement index supports ordering and INCLUDE');
rejects(q{CREATE INDEX partial_idx ON t(x) WHERE x>0},'partial index remains explicitly unsupported');
rejects(q{CREATE INDEX expression_idx ON t((x+1))},'expression index remains explicitly unsupported');
rejects(q{CREATE INDEX CONCURRENTLY concurrent_idx ON t(x)},'concurrent index publication remains explicitly unsupported');
my $peer=$node->background_psql('postgres',on_error_stop=>0);
$peer->query_safe(q{SET statement_timeout='3s'; SET client_min_messages=warning; PREPARE stable AS SELECT id,x,v FROM t ORDER BY id; BEGIN; CREATE INDEX x_idx ON t(v)});
sql(q{BEGIN; CREATE INDEX other_v_idx ON t(v); UPDATE t SET v='other' WHERE x=11});
is($peer->query_safe(q{EXECUTE stable}),"1|10|a\n2|20|b",'other branch prepared scan remains independent during index publication');
$peer->query_safe(q{UPDATE t SET v='main' WHERE id=1; COMMIT});
sql(q{COMMIT});
is(sql(q{SELECT v FROM t WHERE x=11}),'other','parallel branch DML keeps its own index state');
$peer->quit;
sql(q{SELECT dolt_commit('-Am','replacement indexes')});
is(sql(q{SELECT id,x,v FROM t AS OF 'main' ORDER BY id}),"1|10|a\n2|20|b",'AS OF branch HEAD retains committed table and index definitions');
is(sql(q{SELECT indexname FROM pg_indexes AS OF 'HEAD~1' WHERE tablename='t' ORDER BY indexname}),"v_unique\nx_idx",'retained index definitions survive deletion and replacement');
$s->quit;$node->stop('immediate');$node->start;
$s=$node->background_psql('postgres',on_error_stop=>0);
sql(q{SET client_min_messages=warning; SELECT dolt_checkout('other'); SET enable_seqscan=off});
is(sql(q{SELECT x,v FROM t ORDER BY x}),"11|other\n21|b",'WAL recovery restores committed index roots');
sql(q{SELECT dolt_checkout('main')});
is(sql(q{SELECT * FROM t ORDER BY id}),"1|10|main\n2|20|b",'other branch schema and rows unaffected');
$s->quit;$node->stop;done_testing();
