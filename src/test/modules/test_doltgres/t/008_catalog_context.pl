use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('catalog_context');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->start;
sub sql {return $node->safe_psql('postgres',$_[0]);}
sql(q{CREATE ROLE catalog_reader; CREATE TABLE t(id int PRIMARY KEY, value text) USING dolt_prolly_table; INSERT INTO t VALUES(1,'one'); SELECT dolt_commit('-Am','base'); SELECT dolt_checkout('-b','other'); ALTER TABLE t ADD COLUMN extra int; CREATE TABLE only_other(x int); SELECT dolt_commit('-Am','other schema')});
my $s=$node->background_psql('postgres');
$s->query_safe(q{SELECT dolt_checkout('other')});
my $columns=q{SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name='t' ORDER BY ordinal_position};
is($s->query_safe($columns),"id\nvalue\nextra",'stored information schema view uses selected branch');
is(sql($columns),"id\nvalue",'independent session sees main columns');
is($s->query_safe(q{SELECT tablename FROM pg_tables WHERE schemaname='public' ORDER BY tablename}),"only_other\nt",'pg_tables includes canonical-only relations');
is(sql(q{SELECT tablename FROM pg_tables WHERE schemaname='public' ORDER BY tablename}),'t','pg_tables excludes other branch membership');
like($s->query_safe(q{SELECT indexdef FROM pg_indexes WHERE tablename='t'}),qr/CREATE UNIQUE INDEX t_pkey/,'index deparser resolves bound index handles');
$s->query_safe('PREPARE cols AS '.$columns);
is($s->query_safe('EXECUTE cols'),"id\nvalue\nextra",'prepared catalog query binds current definition');
$s->query_safe(q{SELECT dolt_checkout('main')});
is($s->query_safe('EXECUTE cols'),"id\nvalue",'prepared stored catalog view rebinds after checkout');
$s->query_safe(q{BEGIN; ALTER TABLE t ADD COLUMN pending int});
is($s->query_safe($columns),"id\nvalue\npending",'catalog view sees own transactional DDL');
is(sql($columns),"id\nvalue",'catalog view hides uncommitted DDL');
$s->query_safe('ROLLBACK');
is($s->query_safe('EXECUTE cols'),"id\nvalue",'aborted context cannot survive prepared plan');
# Hold a catalog cursor across another session's schema commit.
$s->query_safe('BEGIN ISOLATION LEVEL REPEATABLE READ; DECLARE c CURSOR FOR '.$columns);
is($s->query_safe('FETCH 1 FROM c'),'id','catalog cursor opens in old snapshot');
sql(q{ALTER TABLE t ADD COLUMN later int});
is($s->query_safe('FETCH ALL FROM c'),'value','catalog cursor retains old layout after concurrent DDL');
is($s->query_safe($columns),"id\nvalue",'repeatable-read reparse retains old catalog revision');
$s->query_safe('COMMIT');
is($s->query_safe('EXECUTE cols'),"id\nvalue\nlater",'new snapshot observes committed catalog revision');
my $reader=$node->background_psql('postgres');
$reader->query_safe(q{SET ROLE catalog_reader});
is($reader->query_safe(q{SELECT count(*) FROM information_schema.columns WHERE table_schema='public' AND table_name='t'}),'0','information schema privilege filter does not expose inaccessible columns');
is($reader->query_safe(q{SELECT tablename FROM pg_tables WHERE schemaname='public'}),'t','public table inventory retains native view permissions');
# Views owned by bootstrap owner may inspect otherwise restricted catalogs.
is($reader->query_safe(q{SELECT count(*) FROM pg_stats WHERE schemaname='public'}),'0','stored view owner permissions survive catalog binding');
$reader->quit;
is(sql(q{WITH t AS (SELECT 42 AS id) SELECT id FROM t}),'42','CTE takes precedence over same-named canonical table');
is(sql(q{WITH RECURSIVE t(n) AS (VALUES(1) UNION ALL SELECT n+1 FROM t WHERE n<3) SELECT sum(n) FROM t}),'6','recursive CTE resolves its own name under active branch');
is(sql(q{WITH t AS (SELECT 42 AS id) SELECT id FROM t AS OF 'HEAD'}),'1','explicit revision selects stored relation rather than same-named CTE');
my $before=sql(q{SELECT count(*) FROM pg_dolt_storage});
is(sql(q{BEGIN READ ONLY; WITH cols AS MATERIALIZED (SELECT * FROM information_schema.columns WHERE table_schema='public' AND table_name='t') SELECT column_name FROM cols ORDER BY ordinal_position; COMMIT}),"id\nvalue\nlater",'read-only CTE expansion carries context');
is(sql(q{SELECT count(*) FROM pg_dolt_storage}),$before,'introspection allocates no persistent storage');
is(sql(q{SELECT m.column_name,h.attname FROM information_schema.columns m CROSS JOIN (pg_attribute AS OF 'other' h JOIN pg_class AS OF 'other' c ON h.attrelid=c.oid) WHERE m.table_schema='public' AND m.table_name='t' AND m.column_name='later' AND c.relname='t' AND h.attname='extra'}),'later|extra','stored current view and explicit historical catalogs coexist');
is(sql(q{SELECT c.relname,pg_get_indexdef(i.indexrelid,1,true) FROM pg_index AS OF 'other' i JOIN pg_class AS OF 'other' c ON c.oid=i.indrelid WHERE c.relname='t'}),'t|id','historical bound handles reach native index deparser');
$s->quit;$node->stop;$node->start;
is(sql($columns),"id\nvalue\nlater",'cold restart binds stored views automatically');
$node->stop;done_testing();
